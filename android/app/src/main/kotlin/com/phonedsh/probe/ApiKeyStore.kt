// phone-dsh — :app: the demo host's model-key store and credential seam.
// SPDX-License-Identifier: MIT
//
// This is the Android half of the iOS Keychain credential store
// (`Sources/PhoneDSH/PhoneModelProviderSettings.swift`,
// `KeychainModelProviderSecretStore`, `kSecUseDataProtectionKeychain`). Android
// has no `SecItem`, so the envelope is the one `:platform-android` already owns:
// an AES-GCM key generated inside `AndroidKeyStore`, the ciphertext under
// `Context.noBackupFilesDir/secure-store` — the same wrapping the handoff reclaim
// token uses. The whitelist row `platform.keychain-credential-store` fixes that
// mechanism and explicitly does not depend on the stalled
// `androidx.security-crypto`, so `EncryptedSharedPreferences` is not used.
//
// Why the key is unreadable outside the Keystore:
//   * the AES key is generated by `AndroidKeyStore` and never leaves it —
//     `KeyStore.getKey` on an AndroidKeyStore alias returns a handle, not key
//     material, so even a root-level read of the ciphertext cannot decrypt it
//     while that key lives in StrongBox/TEE;
//   * the ciphertext file lives under `noBackupFilesDir`, which Auto Backup and
//     device transfer skip, and the app's manifest already declares
//     `android:allowBackup="false"` plus explicit exclusions for that path
//     (`res/xml/backup_rules.xml`, `res/xml/data_extraction_rules.xml`);
//   * the Keystore alias is `"pdsh.secure." + SHA-256(account)`, and the alias is
//     bound as GCM additional authenticated data, so a ciphertext moved to a
//     different account fails the tag check instead of decrypting;
//   * nothing on this path logs, and nothing writes plaintext: the only copy of
//     the decoded string is the one [ApiKeyState.Valid] hands to the gateway's
//     `ModelKeySource` (`ModelGatewayCredentialProvider`). The Worker env gets the
//     non-secret `phone-host-injects-mcp-key` placeholder instead, so the Worker
//     never holds the key (`spec/v1/gateway-security.md` §2); the UI path ([fact])
//     only ever sees four characters.
//
// The honest limit: on the last rung of the whitelist's downgrade chain (a device
// whose `AndroidKeyStore` cannot create keys) `AndroidSecureStore` wraps the
// ciphertext with an app-managed `software.key` file in the same no-backup
// directory, so there the protection is the app sandbox alone. [securityLevel]
// reports that level instead of assuming hardware; this store does not hide it.
//
// Three states, never two: [ApiKeyState.Absent] means the host read the store and
// there is no key; [ApiKeyState.Invalid] means a key exists but cannot be used
// (Keystore entry gone, GCM tag failed, stored value blank/short/non-printable);
// [ApiKeyState.Valid] is the only state that may be injected. "Unreadable" is
// deliberately not "absent": treating it as absent would silently drop a real key
// and invite the user to overwrite it (the baseline's `ModelProviderAPIKeyStatus`).
//
// Wiring, owned by the composition root (two lines, both outside this lane):
//   1. `MainActivity.onCreate`, before `ProbeLaunchConfig.install(intent)`:
//        `ApiKeyStore.install(applicationContext)`
//   2. `ProbeEngineViewModel`'s gateway, replacing the anonymous provider:
//        `credentialProvider = launchConfig.modelCredentialProvider() ?: AnonymousCredentialProvider`
// Until (1) runs, the Worker env reports [ApiKeyState.Absent] (no key is
// invented) and the settings page reports `UNKNOWN`; until (2) runs, the gateway
// stays anonymous even though the key is stored.

package com.phonedsh.probe

import android.content.Context
import com.phonedsh.gateway.CredentialUnavailableException
import com.phonedsh.gateway.GatewayCredentialProvider
import com.phonedsh.gateway.ModelEndpoint
import com.phonedsh.gateway.ModelGatewayCredentialProvider
import com.phonedsh.gateway.ModelKeySource
import com.phonedsh.platform.SecureLookup
import com.phonedsh.platform.SecureStore
import com.phonedsh.platform.SecurityLevel
import com.phonedsh.platform.android.AndroidSecureStore
import com.phonedsh.ui.page.ProviderKeyFact
import com.phonedsh.ui.page.ProviderKeyStatus
import com.phonedsh.ui.page.maskKeySuffix
import java.util.concurrent.atomic.AtomicReference
import kotlinx.coroutines.runBlocking

/**
 * What the host knows about the stored model key.
 *
 * [Valid.value] is the only plaintext copy in the process. Every other path is
 * built from [ApiKeyStore.fact], which masks before it leaves the store class.
 */
internal sealed interface ApiKeyState {
    /** The store was read and holds no key for a model service. */
    data object Absent : ApiKeyState

    /**
     * A key exists but cannot be used.
     *
     * [reason] is a display-safe label (`"key-invalidated"`, `"blank-key"`, ...);
     * it never carries key material.
     */
    class Invalid(val reason: String) : ApiKeyState {
        override fun toString(): String = "ApiKeyState.Invalid($reason)"
    }

    /** A read failure: callers must not mistake this for an absent/invalid key. */
    class Unreadable(val reason: String) : ApiKeyState {
        override fun toString(): String = "ApiKeyState.Unreadable($reason)"
    }

    /** The only state that may be injected; [toString] never prints the value. */
    class Valid(val value: String) : ApiKeyState {
        override fun toString(): String = "ApiKeyState.Valid(***)"
    }
}

/**
 * The host's model-key store, over the platform [SecureStore].
 *
 * There is no logger on this class on purpose: the value it handles must not
 * reach logcat, and a diagnostic sink is the usual way one does.
 *
 * @param store the device envelope; `:app` installs
 *   [AndroidSecureStore] and the instrumented suite injects a fake.
 */
internal class ApiKeyStore(private val store: SecureStore) : ModelKeySource {

    /** The strongest protection this device actually gave the wrapping key. */
    val securityLevel: SecurityLevel
        get() = store.level

    /**
     * Reads the three-state key fact.
     *
     * The store is a suspend API because it does file IO; the launch path is
     * synchronous (`ProbeLaunchConfig.workerEnvironment` runs in the composition
     * root), so this blocks on one small file read. There is no network here.
     */
    fun read(account: String = ACCOUNT): ApiKeyState {
        val lookup = try {
            runBlocking { store.get(account) }
        } catch (failure: Exception) {
            return ApiKeyState.Unreadable(REASON_STORE_UNAVAILABLE)
        }
        return when (lookup) {
            is SecureLookup.Found -> classify(lookup.value)
            SecureLookup.Absent -> ApiKeyState.Absent
            is SecureLookup.Unreadable -> ApiKeyState.Unreadable(lookup.reason)
        }
    }

    /**
     * The injection path: the key itself, `null` when absent.
     *
     * @throws CredentialUnavailableException when a key exists but is unusable, so
     *   the gateway fails closed with `credential_unavailable` instead of sending
     *   an anonymous request. The message is constant.
     */
    override fun readKey(): String? = readKey(ACCOUNT)

    /** Injection path for one profile's account. */
    fun readKey(account: String): String? = when (val state = read(account)) {
        is ApiKeyState.Valid -> state.value
        ApiKeyState.Absent -> null
        is ApiKeyState.Invalid, is ApiKeyState.Unreadable -> throw CredentialUnavailableException(KEY_UNUSABLE)
    }

    /**
     * The UI path: a fact with at most four trailing characters.
     *
     * This is the only key-shaped value the page may receive; the page re-masks it
     * through `maskKeySuffix`, so even a mistake here cannot print a whole key.
     */
    fun fact(account: String = ACCOUNT): ProviderKeyFact = when (val state = read(account)) {
        is ApiKeyState.Valid ->
            ProviderKeyFact(ProviderKeyStatus.CONFIGURED, maskKeySuffix(state.value))
        ApiKeyState.Absent -> ProviderKeyFact(ProviderKeyStatus.NOT_CONFIGURED, null)
        is ApiKeyState.Invalid -> ProviderKeyFact(ProviderKeyStatus.INVALID, null)
        is ApiKeyState.Unreadable -> ProviderKeyFact(ProviderKeyStatus.UNKNOWN, null)
    }

    /**
     * Stores [rawKey], replacing any previous value.
     *
     * @throws IllegalArgumentException when [rawKey] is not a usable key. The
     *   message is constant: an exception must not echo the value it rejected.
     * @throws java.io.IOException when the Keystore envelope cannot be written.
     */
    fun save(rawKey: String, account: String = ACCOUNT) {
        val key = rawKey.trim()
        require(isUsable(key)) { "the model key must be printable, at least $MIN_KEY_LENGTH characters long" }
        val bytes = key.toByteArray(Charsets.UTF_8)
        try {
            runBlocking { store.put(account, bytes) }
        } finally {
            // Do not keep a second copy of the secret in this frame's garbage.
            bytes.fill(0)
        }
    }

    /** Removes the stored key; succeeds when nothing was stored. */
    fun clear(account: String = ACCOUNT) {
        runBlocking { store.delete(account) }
        if (read(account) != ApiKeyState.Absent) {
            throw java.io.IOException("the stored key could not be confirmed deleted")
        }
    }

    /**
     * The gateway credential provider for [baseUrl].
     *
     * @param baseUrl the launch's model endpoint (`DEEPSEEK_BASE_URL`); `null` when
     *   it is not an absolute http(s) URL, because a credential must never be
     *   attached to an endpoint the host could not parse.
     * @param anonymousHosts egress hosts that are deliberately key-free.
     */
    fun credentialProvider(
        baseUrl: String,
        anonymousHosts: Set<String> = emptySet(),
        account: String = ACCOUNT,
    ): GatewayCredentialProvider? {
        val endpoint = ModelEndpoint.parse(baseUrl) ?: return null
        return ModelGatewayCredentialProvider(endpoint, ModelKeySource { readKey(account) }, anonymousHosts)
    }

    /**
     * Classifies one stored value.
     *
     * A model key is printable ASCII without inner whitespace (the header grammar
     * it rides forbids it), at least [MIN_KEY_LENGTH] characters — the page's own
     * mask floor, so a "valid" key always has a four-character suffix to show.
     */
    private fun classify(raw: ByteArray): ApiKeyState {
        val text = try {
            String(raw, Charsets.UTF_8).trim()
        } catch (failure: Exception) {
            return ApiKeyState.Invalid(REASON_UNDECODABLE)
        }
        return when {
            text.isEmpty() -> ApiKeyState.Invalid(REASON_BLANK)
            !isUsable(text) -> ApiKeyState.Invalid(REASON_UNUSABLE)
            else -> ApiKeyState.Valid(text)
        }
    }

    private fun isUsable(text: String): Boolean =
        text.length >= MIN_KEY_LENGTH && text.all { it in '!'..'~' }

    companion object {
        /** The `SecureStore` account; hashed into the Keystore alias, never on disk. */
        const val ACCOUNT: String = "model.deepseek.api-key"

        /** Below this, `maskKeySuffix` would be the whole key, so it is not a key. */
        const val MIN_KEY_LENGTH: Int = 8

        private const val KEY_UNUSABLE: String = "the stored model key cannot be read"

        private const val REASON_STORE_UNAVAILABLE: String = "key-store-unavailable"
        private const val REASON_UNDECODABLE: String = "key-undecodable"
        private const val REASON_BLANK: String = "key-blank"
        private const val REASON_UNUSABLE: String = "key-unusable"

        private val installed = AtomicReference<ApiKeyStore?>(null)

        /**
         * Binds the process-wide store to [context]'s `noBackupFilesDir`.
         *
         * Idempotent, so a configuration change or a second Activity cannot
         * replace the store under a running engine. The application context is
         * retained; no Activity is leaked.
         */
        @Synchronized
        fun install(context: Context): ApiKeyStore {
            installed.get()?.let { return it }
            val created = ApiKeyStore(AndroidSecureStore(context.applicationContext))
            installed.set(created)
            return created
        }

        /** The installed store, or `null` when the composition root has not run. */
        /**
         * Imports a key typed into the device once, for development only.
         *
         * The value is read from `<files>/import-key.txt`, handed to [save] (Keystore
         * encryption), and the plaintext file is **deleted immediately**. Nothing here
         * logs the value, and the caller must gate this on `BuildConfig.DEBUG`: this is
         * how a developer seeds a real key without putting it on a command line (where
         * it would land in `ps` output and shell history).
         *
         * @return true when a key was imported and the plaintext file removed.
         */
        fun importDevelopmentKey(context: Context): Boolean {
            val source = java.io.File(context.filesDir, "import-key.txt")
            if (!source.isFile) return false
            return try {
                val raw = source.readText().trim()
                // Delete first: if `save` throws, the plaintext must not survive the attempt.
                source.delete()
                if (raw.isEmpty()) return false
                val store = installed.get() ?: return false
                store.save(raw)
                true
            } catch (error: java.io.IOException) {
                source.delete()
                false
            }
        }

        fun active(): ApiKeyStore? = installed.get()

        /**
         * The state the Worker env builder uses.
         *
         * No installed store means no key path at all: report [ApiKeyState.Absent]
         * rather than inventing a placeholder, which keeps the "unconfigured" path
         * honest for the demo's acceptance runs.
         */
        fun activeState(account: String = ACCOUNT): ApiKeyState =
            installed.get()?.read(account) ?: ApiKeyState.Absent

        /**
         * The state the settings page uses.
         *
         * Without an installed store the host genuinely cannot read the key state,
         * so this is `UNKNOWN` — the page renders 未知, never 未配置.
         */
        fun activeFact(account: String = ACCOUNT): ProviderKeyFact =
            installed.get()?.fact(account) ?: ProviderKeyFact(ProviderKeyStatus.UNKNOWN, null)
    }
}
