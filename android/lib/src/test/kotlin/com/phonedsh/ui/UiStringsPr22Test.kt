class UiStringsPr22Test {
    @Test
    fun `PR22 labels exist, are non-blank and keep the baseline words`() {
        PR22_LABELS.forEach { (name, expected) ->
            val actual = string(name)
            assertTrue("$name is blank", actual.isNotBlank())
            assertEquals("$name diverged from PR22", expected, actual)
        }
    }

    @Test
    fun `Android platform copy names Android storage and actual dependencies`() {
        assertTrue(UiStrings.PROVIDER_CONNECTION_FOOTER.contains("Android Keystore"))
        assertFalse(UiStrings.PROVIDER_CONNECTION_FOOTER.contains("钥匙串"))
        assertFalse(UiStrings.PROVIDER_CONNECTION_FOOTER_EN.contains("Keychain"))
        assertTrue(UiStrings.MCP_AUTH_FOOTER.contains("Android Keystore"))
        assertFalse(UiStrings.MCP_AUTH_FOOTER.contains("钥匙串"))
        assertFalse(UiStrings.LICENSES_SWIFTTERM.contains("SwiftTerm"))
        assertFalse(UiStrings.LICENSES_SWIFT_NIO.contains("swift-nio"))
        assertTrue(UiStrings.SETTINGS_LICENSES_ANDROID_ONLY.contains("AndroidX"))
        assertTrue(UiStrings.SETTINGS_LICENSES_ANDROID_ONLY.contains("Ktor"))
    }

    @Test
    fun `reused labels carry the PR22 wording`() {
        assertEquals(UiStrings.MCP_FIELD_NAME, UiStrings.PROVIDER_NAME_LABEL)
        assertEquals(UiStrings.PROVIDER_KEY_SECTION, UiStrings.PROVIDER_KEY_LABEL)
        assertEquals(UiStrings.PROVIDER_FIELD_ID, UiStrings.PROVIDER_IDENTIFIER_LABEL)
    }

    @Test
    fun `templates match the format calls that render them`() {
        TEMPLATES.forEach { name ->
            val template = string(name)
            val specs = PLACEHOLDER.findAll(template).map { it.groupValues[1] }.toList()
            val args: Array<Any> = Array(specs.size) { index -> if (specs[index] == "d") 1 else "x" }
            val rendered = String.format(Locale.ROOT, template, *args)
            assertFalse("$name left a placeholder after formatting: $rendered",
                PLACEHOLDER.containsMatchIn(rendered))
            assertEquals("$name placeholder arity", specs.size.toLong(), args.size.toLong())
        }
    }

    @Test
    fun `PR22 test tags exist, are non-blank and are unique`() {
        val values = mutableSetOf<String>()
        PR22_TAGS.forEach { (name, expected) ->
            val actual = tag(name)
            assertTrue("$name is blank", actual.isNotBlank())
            assertEquals("$name diverged from PR22", expected, actual)
            assertTrue("duplicate tag value for $name: $actual", values.add(actual))
        }
    }

    @Test
    fun `every declared PR22 string is non-blank`() {
        val names = PR22_LABELS.keys + setOf(
            "PROVIDER_NAME_LABEL", "PROVIDER_KEY_LABEL", "PROVIDER_IDENTIFIER_LABEL",
        )
        names.forEach { assertTrue("$it is blank", string(it).isNotBlank()) }
    }

