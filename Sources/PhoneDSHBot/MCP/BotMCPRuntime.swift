// MARK: - Task authorization subset (P26 §2.5)

public enum BotTaskAuthorizationError: Error, Equatable, CustomStringConvertible {
    case invalidDirectories(String)
    case tooManyDirectories(Int)

    public var description: String {
        switch self {
        case .invalidDirectories(let reason): return "invalid task write authorization: \(reason)"
        case .tooManyDirectories(let limit):
            return "at most \(limit) allowed_write_directories entries are accepted"
        }
    }
}

/// Conservative bash write-target extraction for a Task child. It covers
/// output redirects and the destination operands of common file-writing
/// commands; shell text that hides a write inside an interpreter string is a
/// documented remaining risk, not a reason to permit the obvious cases.
enum ShellWriteTargets {
    private static let lastOperandCommands: Set<String> = ["cp", "mv", "install", "ln"]
    private static let allOperandCommands: Set<String> = [
        "tee", "mkdir", "touch", "rm", "rmdir", "truncate", "chmod", "chown",
    ]
    private static let redirect: NSRegularExpression? = try? NSRegularExpression(
        pattern: #"(?:^|[^0-9&])[0-9]*>>?[ \t]*([^\s;&|<>)`]+)"#)

    static func targets(in command: String) -> [String] {
        var result: [String] = []
        let range = NSRange(command.startIndex..<command.endIndex, in: command)
        for match in redirect?.matches(in: command, range: range) ?? [] {
            guard let targetRange = Range(match.range(at: 1), in: command) else { continue }
            let target = String(command[targetRange])
            if !target.isEmpty, target != "/dev/null", !target.hasPrefix("&") {
                result.append(target)
            }
        }
        let tokens = command.split(whereSeparator: { $0.isWhitespace }).map(String.init)
        for (index, token) in tokens.enumerated() {
            guard allOperandCommands.contains(token) || lastOperandCommands.contains(token) else {
                continue
            }
            let operands = tokens[(index + 1)...].filter { !$0.hasPrefix("-") }
            if allOperandCommands.contains(token) {
                var values = Array(operands)
                if token == "chmod" || token == "chown" { values = Array(values.dropFirst()) }
                result.append(contentsOf: values)
            } else if let destination = operands.last {
                result.append(destination)
            }
        }
        // `dd of=/path` writes the named file.
        for token in tokens where token.hasPrefix("of=") {
            result.append(String(token.dropFirst(3)))
        }
        return result.filter { !$0.isEmpty }
    }
}

/// The capability subset a child Task runs with. It is generated by the host
/// before the task session is created, persisted with the task record and
/// written into the child session's principal capabilities. A child cannot
/// widen it through the Task tool: this revision has no argument that raises
/// network-write or task-delegation.
public struct BotTaskAuthorization: Codable, Sendable, Equatable {
    public static let maximumWriteDirectories = 32
    public static let workspaceCapabilityPrefix = "task.workspace:"
    public static let writeDirectoryPrefix = "task.write-dir:"
    public static let outsideWorkspaceCapability = "task.write-outside-workspace"
    public static let networkWriteCapability = "task.network-write"
    public static let delegateCapability = "task.delegate"
    public static let maximumCapabilityLength = 128

    public var workspaceRoot: String
    public var allowedWriteDirectories: [String]
    public var canWriteOutsideWorkspace: Bool
    public var canNetworkWrite: Bool
    public var canDelegateTasks: Bool

    public init(workspaceRoot: String, allowedWriteDirectories: [String],
                canWriteOutsideWorkspace: Bool, canNetworkWrite: Bool,
                canDelegateTasks: Bool) {
        self.workspaceRoot = workspaceRoot
        self.allowedWriteDirectories = allowedWriteDirectories
        self.canWriteOutsideWorkspace = canWriteOutsideWorkspace
        self.canNetworkWrite = canNetworkWrite
        self.canDelegateTasks = canDelegateTasks
    }

    public var jsonValue: BotJSONValue {
        .object([
            "workspaceRoot": .string(workspaceRoot),
            "allowedWriteDirectories": .array(allowedWriteDirectories.map(BotJSONValue.string)),
            "canWriteOutsideWorkspace": .bool(canWriteOutsideWorkspace),
            "canNetworkWrite": .bool(canNetworkWrite),
            "canDelegateTasks": .bool(canDelegateTasks),
        ])
    }

    /// Capability strings baked into the task session principal. They are also
    /// the only copy the approval gate consults for an already-running task.
    public var capabilities: [String] {
        var values = ["\(Self.workspaceCapabilityPrefix)\(workspaceRoot)"]
        values += allowedWriteDirectories.map { "\(Self.writeDirectoryPrefix)\($0)" }
        if canWriteOutsideWorkspace { values.append(Self.outsideWorkspaceCapability) }
        if canNetworkWrite { values.append(Self.networkWriteCapability) }
        if canDelegateTasks { values.append(Self.delegateCapability) }
        return values
    }

    /// Resolve requested directory strings against the Bot workspace root.
    /// Empty/blank entries and more than 32 entries fail closed; duplicates
    /// collapse to the first occurrence.
    public static func resolve(requestedDirectories: [String],
                               workspaceRoot: String,
                               canNetworkWrite: Bool = false,
                               canDelegateTasks: Bool = false) throws -> BotTaskAuthorization {
        guard requestedDirectories.count <= maximumWriteDirectories else {
            throw BotTaskAuthorizationError.tooManyDirectories(maximumWriteDirectories)
        }
        let root = normalize(workspaceRoot, against: workspaceRoot)
        guard !root.isEmpty else {
            throw BotTaskAuthorizationError.invalidDirectories("工作区根目录为空")
        }
        var directories: [String] = []
        for raw in requestedDirectories {
            let value = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !value.isEmpty else {
                throw BotTaskAuthorizationError.invalidDirectories("目录条目为空")
            }
            let normalized = normalize(value, against: root)
            guard !normalized.isEmpty else {
                throw BotTaskAuthorizationError.invalidDirectories("目录条目规范化后为空")
            }
            guard normalized.count + writeDirectoryPrefix.count <= maximumCapabilityLength else {
                throw BotTaskAuthorizationError.invalidDirectories(
                    "目录条目超出会话权限的长度上限（最多 \(maximumCapabilityLength) 个字符）")
            }
            if !directories.contains(normalized) { directories.append(normalized) }
        }
        if directories.isEmpty { directories = [root] }
        guard root.count + workspaceCapabilityPrefix.count <= maximumCapabilityLength else {
            throw BotTaskAuthorizationError.invalidDirectories(
                "工作区根目录超出会话权限的长度上限")
        }
        let outside = directories.contains { directory in
            directory != root && !directory.hasPrefix(root + "/")
        }
        return BotTaskAuthorization(
            workspaceRoot: root, allowedWriteDirectories: directories,
            canWriteOutsideWorkspace: outside, canNetworkWrite: canNetworkWrite,
            canDelegateTasks: canDelegateTasks)
    }

    /// Rebuild the subset from a task session's capabilities. Returns nil when
    /// the workspace marker is missing, so a task session without an explicit
    /// subset can never be treated as unrestricted.
    public static func from(capabilities: [String]) -> BotTaskAuthorization? {
        guard let workspace = capabilityValue(workspaceCapabilityPrefix, in: capabilities) else {
            return nil
        }
        let directories = capabilities.compactMap { capabilityValue(writeDirectoryPrefix, in: [$0]) }
        let canWriteOutside = capabilities.contains(outsideWorkspaceCapability)
        return BotTaskAuthorization(
            workspaceRoot: workspace,
            allowedWriteDirectories: directories.isEmpty ? [workspace] : directories,
            canWriteOutsideWorkspace: canWriteOutside,
            canNetworkWrite: capabilities.contains(networkWriteCapability),
            canDelegateTasks: capabilities.contains(delegateCapability))
    }

    /// True when `path` resolves inside one of the allowed directories.
    public func allowsWrite(to path: String) -> Bool {
        let candidate = Self.normalize(path, against: workspaceRoot)
        guard !candidate.isEmpty else { return false }
        return allowedWriteDirectories.contains { directory in
            candidate == directory || candidate.hasPrefix(directory + "/")
        }
    }

    private static func capabilityValue(_ prefix: String, in capabilities: [String]) -> String? {
        for capability in capabilities where capability.hasPrefix(prefix) {
            let value = String(capability.dropFirst(prefix.count))
            if !value.isEmpty { return value }
        }
        return nil
    }

    private static func normalize(_ value: String, against root: String) -> String {
        var text = value.trimmingCharacters(in: .whitespacesAndNewlines)
        if text == "~" || text.hasPrefix("~/") {
            text = (text as NSString).expandingTildeInPath
        }
        if !(text as NSString).isAbsolutePath {
            text = (root as NSString).appendingPathComponent(text)
        }
        return (text as NSString).standardizingPath
    }
}

/// Optional task-executor seam that receives the authorization subset at
/// dispatch time. The runtime refuses to dispatch through an executor that
/// does not implement it for a restricted child; the historical `start`
/// method stays for compatibility and is only used with an unrestricted chat
/// parent in tests.
public protocol BotTaskAuthorizing: Actor {
    func start(request: BotTaskRequest,
               authorization: BotTaskAuthorization) async throws -> BotTaskRecord
    func authorization(taskId: String,
                       parent: BotResolvedToolCall) async throws -> BotTaskAuthorization?
}

