    /// Removes registrations past their expiry and revokes their pending
    /// attributions. Public so a test and the maintenance task can force it.
    @discardableResult
    public func pruneExpiredRegistrations() async -> Int {
        let expired = pruneExpiredRegistrationsSync()
        for attribution in expired {
            _ = await gateway.cancelToolCall(id: attribution.id)
        }
        _ = await gateway.attribution.prune()
        return expired.count
    }

    private func pruneExpiredRegistrationsSync() -> [BotAttribution] {
        let timestamp = now()
        let expired = registrations.filter { $0.value.expiresAt <= timestamp }
        guard !expired.isEmpty else { return [] }
        for (key, _) in expired {
            registrations.removeValue(forKey: key)
            registrationArguments.removeValue(forKey: key)
        }
        return expired.map(\.value)
    }

    public func approve(runtimeId: String, sessionId: String? = nil, callId: String, name: String,
                        action: String, detail: String, command: String,
                        argsDigest: String, alwaysScope: String, askAction: String,
                        suppliedEffects: [BotToolEffect]? = nil) async -> BotApprovalOutcome {
        let scope = scopedRuntimeID(runtimeId)
        guard let call = await identityForApproval(runtimeId: runtimeId, sessionId: sessionId, callId: callId),
              bareToolName(call.attribution.name) == bareToolName(name),
              let arguments = registrationArguments[key(scope, call.sessionId, callId)] else {
            return BotApprovalOutcome(ok: false, allowed: false, message: "unattributed")
        }
        guard let suppliedDigest = try? BotArgumentsDigest.validated(argsDigest),
              suppliedDigest == call.attribution.argsDigest,
              let registeredDigest = try? BotArgumentsDigest.string(for: arguments),
              registeredDigest == suppliedDigest else {
            return BotApprovalOutcome(ok: false, allowed: false, message: "stale:digest_mismatch")
        }
        let bareName = bareToolName(name)
        if bareName == "bash", arguments["command"]?.stringValue != command {
            return BotApprovalOutcome(ok: false, allowed: false, message: "stale:command_mismatch")
        }
        if let denial = taskAuthorityDenial(
            call: call, name: bareName, arguments: arguments, command: command) {
            return BotApprovalOutcome(ok: false, allowed: false, message: denial)
        }
        let effects: [BotToolEffect]
        if askAction == "sandbox-escalation" {
            guard bareName == "bash", alwaysScope == "none",
                  let suppliedEffects, suppliedEffects.count == 1,
                  suppliedEffects[0].operation == "sandbox-escalation",
                  !BotResourceNormalizer.normalize(suppliedEffects[0].resource).isEmpty else {
                return BotApprovalOutcome(ok: false, allowed: false, message: "stale:sandbox_effect")
            }
            effects = [BotToolEffect(
                tool: "bash", operation: "sandbox-escalation",
                resource: suppliedEffects[0].resource, target: suppliedEffects[0].target,
                mutability: .write, policy: .ask, label: action, detail: detail)]
        } else {
            effects = await effectsForApproval(
                name: bareName, botID: call.principal.botId,
                arguments: bareName == "bash" ? .object(["command": .string(command)]) : arguments)
        }
        guard ["until", "session", "none"].contains(alwaysScope) else {
            return BotApprovalOutcome(ok: false, allowed: false, message: "stale:always_scope")
        }
        let expectedScope = !effects.isEmpty && effects.allSatisfy { !$0.known } ? "session" : "until"
        guard alwaysScope == expectedScope || alwaysScope == "none" else {
            return BotApprovalOutcome(ok: false, allowed: false, message: "stale:always_scope")
        }
        if effects.isEmpty { return BotApprovalOutcome(ok: true, allowed: true, message: "auto-policy") }
        return await approvals.request(
            call: call, effects: effects, action: action, detail: detail,
            command: command, alwaysScope: alwaysScope,
            persistence: approvalPersistence(for: call), origin: "structural")
    }

    /// Only the resumable background sessions get a durable todo. A `chat`
    /// turn (including a hidden/agent/held wake) still completes inside its
    /// own turn; it keeps the five-minute card so approval continues in place.
    /// `verifier`/`maintainer` are restricted and never ask for a card.
    private func approvalPersistence(for call: BotResolvedToolCall) -> BotApprovalPersistence {
        switch call.principal.kind {
        case .routine, .task: return .durable
        case .chat, .team, .proactive, .watchdog, .verifier, .maintainer:
            return .interactive
        }
    }

    /// Host-side approval for one Bot network write at the `/v1/http` exit.
    ///
    /// Attribution follows the live `bash` identity registration. A normal
    /// shell call registers before the command body; a call the DSH job
    /// registry kept running after its tool result returned keeps that same
    /// registration alive (with a heartbeat) until the job settles. Several
    /// live registrations may belong to the same Bot (for example two
    /// background jobs or a chat and a task session); they are one owner. Only
    /// registrations from different Bots are ambiguous, and the outer command
    /// host text remains a tie-breaker.
    ///
    /// Inside a turn, registration is the authority. With no live
    /// registration at all the fail-closed fallback asks the App whether a
    /// workbench turn is running: if it is, this is workbench traffic
    /// (`notBot`); if not, the write can only be a Bot background task, so one
    /// active Bot owns the card and several Bots fail with
    /// `bot_egress_ambiguous`. No active Bot credential is
    /// `bot_egress_unattributed`.
    ///
    /// After a write is attributed to a session, a Task session without
    /// `task.network-write` is refused with `task_network_write_denied` before
    /// any card is created. The subset was issued by the host at task creation
    /// and cannot be widened by command text, a model argument or a standing
    /// Grant.
    /// `hostAllowed` is the gateway allow-list decision computed before this
    /// seam runs. A Task without `task.network-write` is denied with its named
    /// cause even when the host is outside the allow-list (the Task subset
    /// check is the first, stable answer). Other not-allowed hosts keep the
    /// workbench behaviour and are answered by the gateway's ordinary
    /// `host_not_allowed` failure, without a card.
    public func approveEgress(method: String, host: String, scheme: String,
                              port: Int?,
                              hostAllowed: Bool = true) async -> BotEgressApproval {
        let upper = method.trimmingCharacters(in: .whitespacesAndNewlines).uppercased()
        guard ["POST", "PUT", "PATCH", "DELETE"].contains(upper) else { return .notBot }
        let normalizedHost = host.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        guard !normalizedHost.isEmpty, !scheme.isEmpty else {
            return .denied(
                code: "egress_approval_denied",
                message: "这次网络写入没有可用的目标地址")
        }
        let target = "\(scheme)://\(normalizedHost)\(port.map { ":\($0)" } ?? "")"
        let timestamp = now()
        var active: [(key: String, attribution: BotAttribution,
                      principal: BotGatewayPrincipal)] = []
        var hadLiveRegistration = false
        for (key, attribution) in registrations {
            guard attribution.name == "bash", attribution.expiresAt > timestamp else { continue }
            hadLiveRegistration = true
            guard let principal = await gateway.tokens.lookupSession(attribution.sessionId),
                  principal.incarnation == attribution.incarnation else { continue }
            active.append((key, attribution, principal))
        }
        if hadLiveRegistration && active.isEmpty {
            return .denied(
                code: "bot_egress_unattributed",
                message: "当前 Bot 会话的凭据已经失效")
        }
        if !active.isEmpty {
            let chosen: (key: String, attribution: BotAttribution,
                         principal: BotGatewayPrincipal)
            let groups = Dictionary(grouping: active, by: { $0.principal.botId })
            if groups.count > 1 {
                // A python/git script may not name the host in the outer
                // command, so the host text is only a tie-breaker. Anything
                // still ambiguous fails closed instead of attributing one
                // Bot's write to another.
                let matches = active.filter { entry in
                    commandText(for: entry.key).range(
                        of: normalizedHost, options: [.caseInsensitive]) != nil
                }
                let matchingBots = Set(matches.map { $0.principal.botId })
                guard matchingBots.count == 1, let bot = matchingBots.first,
                      let match = matches.first(where: { $0.principal.botId == bot }) else {
                    return .denied(
                        code: "bot_egress_ambiguous",
                        message: "同时有多个 Bot 会话在运行，无法判断这次网络写入属于谁")
                }
                chosen = match
            } else {
                let candidates = groups.values.first ?? []
                chosen = candidates.first(where: {
                    commandText(for: $0.key).range(
                        of: normalizedHost, options: [.caseInsensitive]) != nil
                }) ?? candidates[0]
            }
            if let denial = taskNetworkWriteDenial(principal: chosen.principal) {
                return denial
            }
            guard hostAllowed else { return .notBot }
            guard let call = BotResolvedToolCall(
                sessionId: chosen.attribution.sessionId, callId: chosen.attribution.callId,
                agentId: chosen.principal.botId, principal: chosen.principal,
                attribution: chosen.attribution) else {
                return .denied(
                    code: "bot_egress_unattributed",
                    message: "当前 Bot 的登记无法对应到唯一的活动身份")
            }
            let effect = BotEgressEffects.egressEffect(
                method: upper, host: normalizedHost, target: target)
            return await requestEgressApproval(
                call: call, effect: effect, command: commandText(for: chosen.key))
        }

        // Fail-closed fallback. It is deliberately consulted only when no live
        // registration attributes the write: an attributed job must never be
        // diverted to another Bot merely because the workbench is busy.
        if await (workbenchTurnProbe?() ?? false) { return .notBot }
        return await unattributedEgressApproval(
            host: normalizedHost, target: target, method: upper,
            hostAllowed: hostAllowed)
    }

    /// One active Bot and no live registration: ask that Bot's user. Several
    /// active Bots (or none) cannot be attributed safely.
    private func unattributedEgressApproval(
        host: String, target: String, method: String, hostAllowed: Bool
    ) async -> BotEgressApproval {
        let principals = await gateway.tokens.activePrincipals()
        let bots = Set(principals.map(\.botId))
        guard !bots.isEmpty else {
            return .denied(
                code: "bot_egress_unattributed",
                message: "没有活动的 Bot 会话可以承接这次网络写入")
        }
        guard bots.count == 1 else {
            return .denied(
                code: "bot_egress_ambiguous",
                message: "同时有多个 Bot 会话在运行，无法判断这次网络写入属于谁")
        }
        // A chat principal is the visible owner of the Bot; without one a task
        // or routine session still receives the card.
        let principal = principals.first(where: { $0.kind == .chat }) ?? principals[0]
        if let denial = taskNetworkWriteDenial(principal: principal) {
            return denial
        }
        guard hostAllowed else { return .notBot }
        guard let call = syntheticEgressCall(principal: principal) else {
            return .denied(
                code: "bot_egress_unattributed",
                message: "当前 Bot 会话没有有效的身份")
        }
        let effect = BotEgressEffects.egressEffect(method: method, host: host, target: target)
        return await requestEgressApproval(
            call: call, effect: effect,
            command: "后台网络写入找不到仍然活动的命令登记")
    }

    /// The Task subset check for one already-attributed egress write. A Task
    /// without `task.network-write` is denied here rather than at the worker
    /// command classifier, which is no longer a security boundary.
    private func taskNetworkWriteDenial(
        principal: BotGatewayPrincipal
    ) -> BotEgressApproval? {
        guard principal.kind == .task,
              !principal.capabilities.contains(BotTaskAuthorization.networkWriteCapability)
        else { return nil }
        return .denied(
            code: "task_network_write_denied",
            message: "Task 子任务没有网络写权限（未授权 task.network-write），这次请求没有发出")
    }

    /// A card-bearing call for the fallback. It is never persisted as an
    /// attribution and never authorizes any tool other than this one egress
    /// effect; it only carries the Bot principal and a stable digest into the
    /// existing approval coordinator.
    private func syntheticEgressCall(principal: BotGatewayPrincipal) -> BotResolvedToolCall? {
        let timestamp = now()
        let callId = "egress-\(UUID().uuidString.lowercased())"
        let digest = (try? BotArgumentsDigest.string(
            for: .object(["command": .string("")])))
            ?? String(repeating: "0", count: 64)
        let attribution = BotAttribution(
            id: "egress-\(UUID().uuidString.lowercased())",
            sessionId: principal.sessionId, incarnation: principal.incarnation,
            callId: callId, name: "bash", argsDigest: digest, runtimeId: nil,
            createdAt: timestamp,
            expiresAt: timestamp + BotApprovalCoordinator.defaultTimeoutMilliseconds + 30_000)
        return BotResolvedToolCall(
            sessionId: principal.sessionId, callId: callId,
            agentId: principal.botId, principal: principal, attribution: attribution)
    }

    private func commandText(for key: String) -> String {
        if case .string(let text)? = registrationArguments[key]?["command"] { return text }
        return ""
    }

    /// Shared bounded wait/cancellation for an attributed call and the
    /// fallback. Egress writes are always durable: a Worker `curl` can abort
    /// while the user is deciding, so holding its `/v1/http` request for the
    /// full 300 s decision window loses the response. A chat write waits only
    /// `egressInteractiveWaitMilliseconds` (so a present user still completes
    /// the same request); after that the card stays pending and the approved
    /// retry consumes its once Grant.
    private func requestEgressApproval(
        call: BotResolvedToolCall, effect: BotToolEffect,
        command: String
    ) async -> BotEgressApproval {
        let cancellation = BotEgressApprovalCancellation(approvals: approvals)
        let isChat = call.principal.kind == .chat
        let outcome = await withTaskCancellationHandler {
            let result = await approvals.request(
                call: call, effects: [effect],
                action: effect.label, detail: effect.detail,
                command: command, alwaysScope: "until",
                persistence: .durable, origin: "egress",
                onPending: { id in cancellation.set(approvalID: id) },
                interactiveWaitMilliseconds: isChat
                    ? egressInteractiveWaitMilliseconds : 0)
            cancellation.clear()
            return result
        } onCancel: {
            cancellation.cancel()
        }
        if outcome.pending {
            // The original HTTP write is not retried here: the durable once
            // Grant must survive for the retried request. A task/routine has a
            // parked host turn that the decision wakes; a chat retry is the
            // model's (or user's) next call.
            if !isChat {
                let pendingState = await approvals.pendingApproval(
                    sessionId: call.sessionId)
                let recentState = pendingState == nil
                    ? await approvals.pendingOrRecentApproval(
                        sessionId: call.sessionId) : nil
                if let state = pendingState ?? recentState {
                    await dispatchApprovalPending(state)
                }
            }
            // Keep the frozen egress taxonomy: the loopback layer maps
            // `egress_approval_denied` to 403/`xl_error.code`. The message is
            // what tells the model that a durable decision authorizes a retry.
            return .denied(
                code: "egress_approval_denied",
                message: isChat
                    ? "已提交审批，批准后请重试；这次网络写入没有发出"
                    : "审批还在等待用户确认；这次网络写入没有发出，用户决定后会继续")
        }
        guard outcome.allowed else {
            return .denied(
                code: "egress_approval_denied",
                message: outcome.message ?? "用户没有批准这次网络写入")
        }
        // A fresh durable allowOnce leaves its Grant for this request to
        // consume: if the request was aborted while the user decided, the
        // Grant must survive for the retry; if it is still alive, consume it
        // before the gateway writes so a concurrent retry cannot reuse it.
        if !outcome.onceGrantIDs.isEmpty, !Task.isCancelled {
            guard await approvals.consumeOnceGrants(outcome.onceGrantIDs) else {
                return .denied(
                    code: "egress_approval_denied",
                    message: "这次审批已经被另一次重试使用，请重新发起网络写入")
            }
        }
        return .allowed
    }

    public func execute(name: String, arguments: BotJSONValue,
                        context: BotMCPRequestContext) async -> BotMCPCallResult {
        let bareName = bareToolName(name)
        let catalogTool = BotToolCatalog.isRegistered(bareName)
        let teamHandler = catalogTool ? nil : teamToolHandler(for: bareName)
        guard catalogTool || teamHandler != nil else {
            return .failure("unknown_tool", "未知工具：\(name)")
        }
        let scope = scopedRuntimeID(context.runtimeId)
        guard let call = await gateway.resolveToolCall(
            runtimeId: scope, name: bareName, arguments: arguments) else {
            return .failure("unattributed", "这次工具调用无法归属到任何进行中的会话")
        }
        // The per-caller catalog is not a display filter: `tools/call` must use
        // the same catalog `tools/list` returns for this principal before any
        // effect or handler runs. `CreateTeammate`'s main-Bot check below stays
        // a second, independent check.
        let callerCatalog = await toolDefinitions(callerBotID: call.principal.botId)
        guard callerCatalog.contains(where: { $0.name == bareName }) else {
            return .failure("permission_denied",
                            "这个工具不在当前 Bot 的可用工具里")
        }
        let registrationKey = key(scope, call.sessionId, call.callId)
        registrations.removeValue(forKey: registrationKey)
        registrationArguments.removeValue(forKey: registrationKey)
        // A replaced Worker keeps its MCP client call open until the App
        // answers. While the App is still reattaching the transport there is
        // nothing that can complete Task/AwaitTask/StopSubagent or an
        // approval/card call; the bounded probe turns that into a normal tool
        // error instead of the Worker's 130 s `Request timed out`. Native
        // tools were forwarded by `BotMCPHandler` before this method.
        if let runtimeReadinessProbe {
            let ready = await runtimeReadinessProbe(0)
            guard ready else {
                return .failure("unavailable", Self.runtimeRecoveringMessage)
            }
        }
        do {
            if bareName == BotToolCatalog.volatileContextName {
                let read = BotToolEffect(
                    tool: bareName, operation: "context.volatile", resource: "session=\(call.sessionId)",
                    mutability: .read, policy: .auto, label: "读取当前上下文")
                guard await authorize(call: call, effect: read) == nil else {
                    return .failure("permission_denied", "读取当前上下文的授权失败")
                }
                let snapshot = try await volatileContext.snapshot(request: arguments, principal: call.principal)
                return .success(snapshot.jsonValue)
            }
            let effect = BotToolEffectClassifier.effect(for: bareName, arguments: arguments)
            if let reason = await authorize(call: call, effect: effect) {
                return .failure("permission_denied", reason)
            }
            if let teamHandler {
                if bareName == BotTeamTools.createTeammateName {
                    var authority = turnAuthority(for: call)
                    if !authority.isUserTurn {
                        let name = string(arguments["name"]) ?? "unnamed"
                        let resource = "teammate:create:\(BotResourceNormalizer.normalize(name))"
                        let effect = BotToolEffect(
                            tool: bareName, operation: "teammate.authorize",
                            resource: resource, target: resource, mutability: .write,
                            policy: .ask, label: "确认创建队友 Bot「\(name)」",
                            detail: "\(authority.approvalSourceDescription)；创建队友会让模型给另一个 Bot 设目标。",
                            known: false, isMcp: true)
                        let outcome = await approvals.request(
                            call: call, effects: [effect], action: "CreateTeammate",
                            detail: effect.detail, command: "", alwaysScope: "none",
                            persistence: approvalPersistence(for: call), origin: "structural")
                        guard outcome.allowed else {
                            return .failure(
                                "permission_denied",
                                outcome.pending
                                    ? "审批还在等待用户确认；任务已经停下，用户决定后会继续"
                                    : outcome.message ?? "创建队友需要你在当前回合确认")
                        }
                        authority.approvalID = outcome.approvalId
                    }
                    if let authorized = teamHandler as? any BotTurnAuthorizedTeamToolHandling {
                        return await authorized.execute(
                            name: bareName, arguments: arguments,
                            principal: call.principal, context: context, authority: authority)
                    }
                }
                return await teamHandler.execute(
                    name: bareName, arguments: arguments,
                    principal: call.principal, context: context)
            }
            return try await dispatch(name: bareName, arguments: arguments, call: call)
        } catch let error as BotMCPError {
            return .failure(Self.code(error), Self.message(error))
        } catch let error as BotCardPayloadError {
            switch error {
            case .invalid(let message): return .failure("invalid_arguments", message)
            }
        } catch {
            return .failure("execution_failed", String(describing: error))
        }
    }

    private func authorize(call: BotResolvedToolCall, effect: BotToolEffect) async -> String? {
        let decision = await authorizer.authorizeExecution(
            principal: BotExecutionPrincipal(gateway: call.principal), effects: [effect],
            source: "app-mcp-execution", argsDigest: call.attribution.argsDigest)
        return decision.allowed ? nil : decision.reason
    }

    private func dispatch(name: String, arguments: BotJSONValue,
                          call: BotResolvedToolCall) async throws -> BotMCPCallResult {
        if BotToolCatalog.cardToolNames.contains(name) {
            let built = try BotCardPayloads.build(tool: name, arguments: arguments)
            let final = try BotCardPayloads.contentCardFinal(tool: name, arguments: arguments)
            guard case .object(let result) = built, let card = result["card"] else {
                throw BotMCPError.invalidRequest("card builder returned no card")
            }
            var fields = card.objectValue ?? [:]
            fields["card"] = card
            fields["id"] = .string("card-\(UUID().uuidString.lowercased())")
            fields["tool"] = .string(name)
            fields["callId"] = .string(call.callId)
            _ = try await eventWriter.append(type: "card.presented", principal: call.principal, data: .object(fields))
            if final {
                // Same seam as ask_user/show_next_steps: a successful wrap-up
                // card suppresses SendToUser for the rest of the turn. It does
                // not cancel the turn and does not alter the card payload.
                suppressingTextSessions.insert(call.sessionId)
            }
            if name == "ask_user" || name == "show_next_steps" {
                suppressingTextSessions.insert(call.sessionId)
                let text = name == "ask_user"
                    ? "已显示提问卡；回合应在此结束，等待用户选择。"
                    : "已显示建议下一步卡片；回合应在此结束，等待用户选择。"
                return .success(built, text: text)
            }
            return .success(built)
        }
        switch name {
        case "UpdateMemory": return try await updateMemory(arguments, call: call)
        case "ReadMemory": return try await readMemory(arguments, call: call)
        case "RecallMemory": return try await recallMemory(arguments, call: call)
        case "Task": return try await startTask(arguments, call: call)
        case "AwaitTask": return try await awaitTask(arguments, call: call)
        case "StopSubagent": return try await stopTask(arguments, call: call)
        case "UpdateRoutine": return try await updateRoutine(arguments, call: call)
        case "ListRoutines": return .success(try await BotRoutineTool.list(machine: routineMachine, principal: call.principal))
        case "RequestApproval": return try await requestApproval(arguments, call: call)
        case BotToolCatalog.attachToModelName:
            return try await attachToModel(arguments, call: call)
        case "SendToUser": return try await sendToUser(arguments, call: call)
        default: throw BotMCPError.unknownTool(name)
        }
    }

    /// Hand one existing image to the model as an MCP image block. The DSH MCP
    /// client verifies the selected model route declares image input, admits
    /// the bytes through the durable attachment store and only then turns it
    /// into an `ImageBlock`; a text-only model gets a diagnostic instead of a
    /// silent image. Approval is a separate structural effect on this call.
    private func attachToModel(_ arguments: BotJSONValue,
                               call: BotResolvedToolCall) async throws -> BotMCPCallResult {
        guard let reader = modelImageReader else {
            return .failure("unsupported", "当前部署不支持把图片交给模型")
        }
        guard case .object(let args) = arguments else {
            throw BotMCPError.invalidRequest("arguments must be an object")
        }
        let path = string(args["path"])?.trimmingCharacters(in: .whitespacesAndNewlines)
        let fileID = string(args["fileId"])?.trimmingCharacters(in: .whitespacesAndNewlines)
        let photoID = string(args["photoId"])?.trimmingCharacters(in: .whitespacesAndNewlines)
        let sources = [path, fileID, photoID].filter { !($0 ?? "").isEmpty }
        guard sources.count == 1 else {
            throw BotMCPError.invalidRequest("attach_to_model 需要 path、fileId 或 photoId 其中之一")
        }
        let page = (args["page"]?.numberValue).map { max(1, Int($0)) }
        let purpose = string(args["purpose"])?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        guard !purpose.isEmpty else {
            throw BotMCPError.invalidRequest("attach_to_model 需要 purpose")
        }
        let used = modelImageCounts[call.sessionId, default: 0]
        guard used < BotModelImagePolicy.maxImagesPerTurn else {
            return .failure("too_many_images",
                            "一条消息最多附 \(BotModelImagePolicy.maxImagesPerTurn) 张图片给模型")
        }
        let image: BotModelImage
        do {
            image = try await reader(BotModelAttachmentRequest(
                path: (path ?? "").isEmpty ? nil : path,
                fileID: (fileID ?? "").isEmpty ? nil : fileID,
                photoID: (photoID ?? "").isEmpty ? nil : photoID,
                page: page,
                purpose: purpose))
        } catch {
            return .failure("image_unavailable",
                            "无法读取这张图片：\(error.localizedDescription)")
        }
        modelImageCounts[call.sessionId] = used + 1
        let summary = "已附上图片 \(image.name)（\(image.pixelWidth)x\(image.pixelHeight)，"
            + "\(image.data.count) bytes）。用途：\(purpose)"
        let structured: BotJSONValue = .object([
            "ok": .bool(true), "kind": .string("image"), "name": .string(image.name),
            "bytes": .number(Double(image.data.count)),
            "width": .number(Double(image.pixelWidth)),
            "height": .number(Double(image.pixelHeight)),
        ])
        return BotMCPCallResult(
            content: [
                .object(["type": .string("text"), "text": .string(summary)]),
                BotModelImagePreparer.mcpJSONValue(image),
            ],
            structuredContent: structured)
    }

    /// Turn origin decides the memory trust. A turn without a registered
    /// origin is `unknown` and keeps the lowest trust (`agent-message`); the
    /// session kind is not a fallback. For a registered origin, `join` can only
    /// downgrade from `userTurn`, so a stale origin can never upgrade the
    /// session-derived source.
    private func memorySourceKind(for call: BotResolvedToolCall) -> BotMemorySourceKind {
        if maintenanceBatches[call.sessionId] != nil { return .maintenance }
        guard let origin = turnOrigins[call.sessionId] else { return .agentMessage }
        var state = BotMemorySourceState(kind: memorySource(call))
        state.join(origin.memorySource)
        return state.kind
    }

    private func updateMemory(_ arguments: BotJSONValue, call: BotResolvedToolCall) async throws -> BotMCPCallResult {
        // A verifier is read-only by contract; the Worker preset/guard already
        // deny UpdateMemory, and this independent check keeps a direct MCP call
        // from writing memory if that surface is ever widened.
        guard call.principal.kind != .verifier else {
            return .failure("permission_denied", "验证会话不能写记忆")
        }
        guard case .object(let args) = arguments else { throw BotMCPError.invalidRequest("arguments must be an object") }
        guard let actionName = string(args["action"]), let action = BotMemoryAction(rawValue: actionName) else {
            throw BotMCPError.invalidRequest("更新记忆需要指定动作：write、append、replace、move、delete 或 restore")
        }
        guard let path = string(args["path"]), !path.isEmpty else {
            throw BotMCPError.invalidRequest("更新记忆需要提供路径")
        }
        guard let expectedVersion = try optionalInt(args["expected_version"]), expectedVersion >= 0 else {
            throw BotMCPError.invalidRequest("更新记忆需要提供不小于 0 的版本号")
        }
        let evidence: BotRecordEvidence
        do {
            evidence = try await validatedEvidence(args, call: call)
                ?? BotRecordEvidence(trust: .assistant, refs: [])
        } catch BotRecordServiceError.erasedRecord {
            // S6: an erased record://event reference is not a normal
            // ownership/syntax failure. Keep the explicit phone-record code so
            // a maintainer (and the main chat) cannot mistake it for a
            // retryable evidence mistake or silently downgrade trust.
            return .failure("record_erased", "该记录已被抹除")
        } catch {
            return .failure("memory-evidence-invalid",
                            "每条依据都必须指向这个 Bot 已有的一条 record:// 记录，或者是真实用户回合里的 current-user-turn。")
        }
        let sourceKind = memorySourceKind(for: call)
        guard let authorKind = call.principal.kind.memoryAuthorKind else {
            return .failure("permission_denied", "验证会话不能写记忆")
        }
        let content: String?
        switch action {
        case .write, .append:
            guard args["content"] != nil else {
                throw BotMCPError.invalidRequest("更新记忆的 \(action.rawValue) 动作需要提供内容")
            }
            content = string(args["content"]) ?? ""
        case .replace:
            guard let find = string(args["find"]), !find.isEmpty else {
                throw BotMCPError.invalidRequest("更新记忆的替换动作需要提供要查找的原文")
            }
            guard args["replace"] != nil else {
                throw BotMCPError.invalidRequest("更新记忆的替换动作需要提供替换后的内容")
            }
            content = nil
        default:
            content = nil
        }
        if action == .move {
            guard let to = string(args["to"]), !to.isEmpty else {
                throw BotMCPError.invalidRequest("更新记忆的移动动作需要提供目标路径")
            }
        }
        let restoreVersion: Int?
        if action == .restore {
            guard let restore = try optionalInt(args["restore_version"]), restore >= 1 else {
                throw BotMCPError.invalidRequest("恢复记忆需要提供不小于 1 的版本号")
            }
            restoreVersion = restore
        } else {
            restoreVersion = nil
        }
        let request = BotMemoryWriteRequest(
            action: action,
            path: path,
            content: content,
            find: action == .replace ? string(args["find"]) : nil,
            replace: action == .replace ? (string(args["replace"]) ?? "") : nil,
            to: action == .move ? string(args["to"]) : nil,
            expectedVersion: expectedVersion,
            restoreVersion: restoreVersion,
            evidence: evidence.refs)
        let context = BotMemoryWriteContext(
            botID: call.principal.botId,
            sessionID: call.principal.sessionId,
            authorKind: authorKind,
            source: BotMemorySource(
                kind: sourceKind,
                sessionID: call.principal.sessionId,
                turnID: turnIDs[call.sessionId],
                role: call.principal.kind.rawValue),
            trust: evidence.trust,
            isMainBot: mainBotProvider(call.principal.botId),
            batchID: maintenanceBatches[call.sessionId])
        let result = try await memory(for: call.principal.botId).write(request, context: context)
        if result.ok, args["marked_contradiction"]?.boolValue == true,
           let version = result.version, let scope = result.scope {
            _ = try? await eventWriter.append(
                type: "memory.review_requested",
                principal: call.principal,
                data: .object([
                    "path": .string(result.path),
                    "scope": .string(scope.rawValue),
                    "version": .number(Double(version)),
                    "evidence": .array(evidence.refs.map(BotJSONValue.string)),
                    "marked_at_ms": .number(Double(now())),
                ]),
                eventId: "memory.review_requested:\(call.principal.botId):\(result.path):\(version)")
        }
        var output: [String: BotJSONValue] = [
            "ok": .bool(result.ok),
            "action": .string(result.action.rawValue),
            "path": .string(result.path),
        ]
        if let scope = result.scope { output["scope"] = .string(scope.rawValue) }
        if let version = result.version { output["version"] = .number(Double(version)) }
        if let previous = result.previousVersion { output["previous_version"] = .number(Double(previous)) }
        if let replaced = result.replaced { output["replaced"] = .number(Double(replaced)) }
        if let code = result.code { output["code"] = .string(code) }
        if let error = result.error { output["error"] = .string(error) }
        if let current = result.currentVersion { output["current_version"] = .number(Double(current)) }
        if let limit = result.limit { output["limit"] = .number(Double(limit)) }
        if let actual = result.actual { output["actual"] = .number(Double(actual)) }
        return .success(.object(output))
    }

    /// Validates the optional evidence array. `nil` means the call supplied
    /// none; malformed, foreign or missing references throw so the caller can
    /// fail the write without downgrading it.
    ///
    /// The reserved `current-user-turn` item is resolved from the reference the
    /// host observed on the live session/follow stream, then stored in its
    /// canonical place among the caller's other evidence. Explicit references
    /// still go through `BotRecordEvidenceResolving` exactly as before; the
    /// host-observed reference is never accepted from model input.
    private func validatedEvidence(_ arguments: [String: BotJSONValue],
                                   call: BotResolvedToolCall) async throws -> BotRecordEvidence? {
        guard let raw = arguments["evidence"] else { return nil }
        guard case let .array(values) = raw,
              values.count <= BotRecordService.maximumEvidence else {
            throw BotRecordServiceError.invalidArguments
        }
        var refs: [String] = []
        var explicitRefs: [String] = []
        var hostCurrentRef: String?
        for value in values {
            guard let text = value.stringValue else {
                throw BotRecordServiceError.invalidReference
            }
            if text == BotMemoryAuthorizer.currentUserTurnEvidence {
                let reference = try await resolveCurrentUserTurnEvidence(call: call)
                if hostCurrentRef == nil {
                    hostCurrentRef = reference
                    refs.append(reference)
                }
                continue
            }
            guard let reference = BotRecordReference.parse(text) else {
                throw BotRecordServiceError.invalidReference
            }
            let canonical = reference.canonical
            refs.append(canonical)
            explicitRefs.append(canonical)
        }
        guard !refs.isEmpty else { return nil }
        var trust = BotRecordTrust.assistant
        if !explicitRefs.isEmpty {
            guard let resolver = recordEvidence else {
                throw BotRecordServiceError.unavailable("record evidence resolver is not attached")
            }
            trust = try await resolver.resolveEvidence(
                explicitRefs, callerBotID: call.principal.botId,
                callerSessionID: call.principal.sessionId).trust
        }
        if hostCurrentRef != nil { trust = .user }
        return BotRecordEvidence(trust: trust, refs: refs)
    }

    /// Resolve the reserved `current-user-turn` evidence item from the host's
    /// live observation of this turn's user message. The turn authority and
    /// the session/seq pair come from the host; a hidden, held, agent, routine,
    /// Task or maintainer turn has no user-turn authority and fails closed.
    /// `beginTurn`/`endTurn` clear the observation, so it cannot cross turns.
    private func resolveCurrentUserTurnEvidence(call: BotResolvedToolCall) async throws -> String {
        let authority = turnAuthority(for: call)
        guard authority.isUserTurn,
              let reference = currentUserMessageRefs[call.sessionId] else {
            throw BotRecordServiceError.sessionOutOfScope
        }
        return reference
    }

    private func readMemory(_ arguments: BotJSONValue, call: BotResolvedToolCall) async throws -> BotMCPCallResult {
        guard case .object(let args) = arguments else { throw BotMCPError.invalidRequest("arguments must be an object") }
        guard let path = string(args["path"]), !path.isEmpty else {
            throw BotMCPError.invalidRequest("读取记忆需要提供路径")
        }
        let version = try optionalInt(args["version"])
        let result = try await memory(for: call.principal.botId).read(path: path, version: version)
        switch result {
        case let .document(document):
            var output: [String: BotJSONValue] = [
                "ok": .bool(true),
                "kind": .string("document"),
                "path": .string(document.path),
                "scope": .string(document.scope.rawValue),
                "version": .number(Double(document.version)),
                "content": .string(document.content),
                "updated_at_ms": .number(Double(document.updatedAtMS)),
                "author": try encode(document.author),
                "evidence": .array(document.evidence.map(BotJSONValue.string)),
            ]
            if let trust = document.trust { output["trust"] = .string(trust) }
            if document.deleted {
                output["deleted"] = .bool(true)
                output["deletion_reason"] = .string(document.deletionReason ?? "forget")
            }
            return .success(.object(output))
        case let .directory(path, scope, entries):
            return .success(.object([
                "ok": .bool(true),
                "kind": .string("directory"),
                "path": .string(path),
                "scope": .string(scope.rawValue),
                "entries": .array(entries.map { entry in
                    var value: [String: BotJSONValue] = [
                        "path": .string(entry.path),
                        "name": .string(entry.name),
                        "kind": .string(entry.kind.rawValue),
                    ]
                    if let version = entry.version { value["version"] = .number(Double(version)) }
                    if let updated = entry.updatedAtMS {
                        value["updated_at_ms"] = .number(Double(updated))
                    }
                    return .object(value)
                }),
            ]))
        case let .failure(code, error, _):
            return .success(.object([
                "ok": .bool(false),
                "code": .string(code),
                "error": .string(error),
            ]))
        }
    }

    private func recallMemory(_ arguments: BotJSONValue, call: BotResolvedToolCall) async throws -> BotMCPCallResult {
        guard case .object(let args) = arguments else { throw BotMCPError.invalidRequest("arguments must be an object") }
        let memory = memory(for: call.principal.botId)
        let limit = try optionalInt(args["limit"]) ?? 40
        guard (1...50).contains(limit) else { throw BotMCPError.invalidRequest("回想记忆的条数必须在 1 到 50 之间") }
        let requestedScope = string(args["scope"]) ?? "all"
        guard ["agent", "user", "all"].contains(requestedScope) else {
            throw BotMCPError.invalidRequest("invalid memory scope")
        }
        let recallScope: BotMemoryScope?
        switch requestedScope {
        case "agent": recallScope = .agent
        case "user": recallScope = .user
        default: recallScope = nil
        }
        let page: (hits: [BotMemoryRecallHit], total: Int)
        do {
            page = try await memory.recallPage(
                string(args["query"]) ?? "", limit: limit, scope: recallScope)
        } catch {
            // A memory read failure is a normal tool error, never a hung
            // turn. Keep the internal error out of the model/user surface.
            return .failure(
                "memory_unavailable",
                "记忆暂时读不出来，请稍后重试。")
        }
        return .success(.object([
            "ok": .bool(true),
            "hits": .array(try page.hits.map { try encode($0) }),
            "count": .number(Double(page.hits.count)),
            "total": .number(Double(page.total)),
            "truncated": .bool(page.total > page.hits.count),
        ]))
    }

    private func startTask(_ arguments: BotJSONValue, call: BotResolvedToolCall) async throws -> BotMCPCallResult {
        guard call.principal.kind == .chat || call.principal.kind == .task else {
            throw BotMCPError.invalidRequest("只有聊天或任务会话可以派发任务")
        }
        // A child Task may only delegate when its own authorization subset says
        // so. This revision never grants that capability, so a subagent cannot
        // keep spawning siblings.
        if call.principal.kind == .task,
           !call.principal.capabilities.contains(BotTaskAuthorization.delegateCapability) {
            return .failure(
                "permission_denied",
                "当前任务会话里不能再派发任务")
        }
        guard case .object(let args) = arguments else { throw BotMCPError.invalidRequest("arguments must be an object") }
        guard args["task_id"] == nil, args["resume"] == nil else {
            throw BotMCPError.invalidRequest("暂不支持从历史任务继续")
        }
        let title = firstNonEmpty(args["task_title"], args["description"]) ?? "委派的任务"
        guard let prompt = firstNonEmpty(args["prompt"], args["task_description"]), !prompt.isEmpty else {
            throw BotMCPError.invalidRequest("派发任务需要说明要做什么")
        }
        let timeout = try optionalInt(args["timeout_ms"]) ?? 180_000
        guard (1_000...300_000).contains(timeout) else { throw BotMCPError.invalidRequest("任务超时必须在 1000 到 300000 毫秒之间") }
        let completion = (string(args["completion"]) ?? "")
            .trimmingCharacters(in: .whitespacesAndNewlines)
        guard completion.count <= 4_000 else {
            throw BotMCPError.invalidRequest("任务的完成条件最多 4000 个字符")
        }
        let purpose = string(args["purpose"])?.trimmingCharacters(in: .whitespacesAndNewlines)
        guard (purpose?.count ?? 0) <= 2_000 else {
            throw BotMCPError.invalidRequest("任务的用途说明最多 2000 个字符")
        }
        let constraints = (args["constraints"]?.arrayValue ?? []).compactMap { value -> String? in
            guard let text = value.stringValue else { return nil }
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            return trimmed.isEmpty ? nil : trimmed
        }
        guard constraints.count <= 8, constraints.allSatisfy({ $0.count <= 500 }) else {
            throw BotMCPError.invalidRequest("任务约束最多 8 条，每条最多 500 个字符")
        }
        var budget: BotTaskBudget?
        if let rawBudget = args["budget"], rawBudget != .null {
            guard case .object(let fields) = rawBudget,
                  fields.keys.allSatisfy({ $0 == "max_duration_ms" }) else {
                throw BotMCPError.invalidRequest("任务预算只接受 max_duration_ms")
            }
            let duration = try optionalInt(fields["max_duration_ms"])
            if let duration {
                guard (BotTaskBudget.minimumDurationMs...BotTaskBudget.maximumDurationMs).contains(duration) else {
                    throw BotMCPError.invalidRequest("任务预算的 max_duration_ms 必须在 1000 到 300000 毫秒之间")
                }
            }
            budget = BotTaskBudget(maxDurationMs: duration)
        }
        let requestedDirectories = (args["allowed_write_directories"]?.arrayValue ?? [])
            .compactMap(\.stringValue)
        guard requestedDirectories.count <= BotTaskAuthorization.maximumWriteDirectories else {
            throw BotMCPError.invalidRequest(
                "allowed_write_directories accepts at most \(BotTaskAuthorization.maximumWriteDirectories) entries")
        }
        let requestedAuthorization = BotTaskAuthorization(
            workspaceRoot: "", allowedWriteDirectories: requestedDirectories,
            canWriteOutsideWorkspace: false, canNetworkWrite: false,
            canDelegateTasks: false)
        let request = BotTaskRequest(
            parent: call, title: title, prompt: prompt,
            asynchronous: bool(args["async"]) ?? false, timeoutMs: timeout,
            completion: completion, purpose: purpose,
            constraints: constraints, budget: budget)
        let executor = try taskExecutor(for: call.principal.botId)
        let record: BotTaskRecord
        let authorization: BotTaskAuthorization
        if let authorizing = executor as? any BotTaskAuthorizing {
            record = try await authorizing.start(
                request: request, authorization: requestedAuthorization)
            let resolved = try await authorizing.authorization(
                taskId: record.taskId, parent: call)
            authorization = resolved ?? requestedAuthorization
        } else {
            // Compatibility executor (tests and the unimplemented default):
            // no session is created, so the host still reports a resolved
            // subset, but nothing can rely on it without the real executor.
            let fallbackRoot = BotWorkspaceLayout.botRoot(
                botId: call.principal.botId, dataDirectory: dataRoot)
            authorization = (try? BotTaskAuthorization.resolve(
                requestedDirectories: requestedDirectories, workspaceRoot: fallbackRoot))
                ?? requestedAuthorization
            record = try await executor.start(request: request)
        }
        // The production task executor persists `task.created` itself, before
        // it starts any work (BotDSHRemoteRuntime.start). Writing a second
        // event here would either race the durable snapshot or leave a crash
        // window with a running task that has no record.
        let taskPrincipal = BotGatewayPrincipal(
            botId: call.principal.botId, sessionId: record.sessionId, kind: .task,
            capabilities: call.principal.capabilities, expiresAt: call.principal.expiresAt)
        _ = try await eventWriter.append(type: "task.started", principal: taskPrincipal, data: record.jsonValue)
        if ["completed", "failed", "stopped"].contains(record.status) {
            _ = try await eventWriter.append(
                type: "task.settled", principal: taskPrincipal, data: record.jsonValue,
                eventId: "settled:\(record.taskId)")
        }
        return .success(taskResult(record.jsonValue, authorization: authorization))
    }

    private func awaitTask(_ arguments: BotJSONValue, call: BotResolvedToolCall) async throws -> BotMCPCallResult {
        guard case .object(let args) = arguments, let id = string(args["task_id"]), !id.isEmpty else {
            throw BotMCPError.invalidRequest("等待任务需要提供任务编号")
        }
        let timeout = try optionalInt(args["timeout_ms"]) ?? 180_000
        guard (1_000...600_000).contains(timeout) else { throw BotMCPError.invalidRequest("等待任务的超时必须在 1000 到 600000 毫秒之间") }
        let executor = try taskExecutor(for: call.principal.botId)
        let record = try await executor.await(taskId: id, timeoutMs: timeout, parent: call)
        if ["completed", "failed", "stopped"].contains(record.status) {
            let principal = BotGatewayPrincipal(
                botId: call.principal.botId, sessionId: record.sessionId, kind: .task, expiresAt: Int64.max)
            _ = try await eventWriter.append(
                type: "task.settled", principal: principal, data: record.jsonValue,
                eventId: "settled:\(record.taskId)")
        }
        var authorization: BotTaskAuthorization?
        if let authorizing = executor as? any BotTaskAuthorizing {
            authorization = try? await authorizing.authorization(taskId: id, parent: call)
        }
        guard let authorization else { return .success(record.jsonValue) }
        return .success(taskResult(record.jsonValue, authorization: authorization))
    }

    private func stopTask(_ arguments: BotJSONValue, call: BotResolvedToolCall) async throws -> BotMCPCallResult {
        guard case .object(let args) = arguments else { throw BotMCPError.invalidRequest("arguments must be an object") }
        guard let id = firstNonEmpty(args["task_id"], args["id"]), !id.isEmpty else {
            throw BotMCPError.invalidRequest("停止任务需要提供任务编号")
        }
        let record = try await taskExecutor(for: call.principal.botId)
            .stop(taskId: id, parent: call)
        let principal = BotGatewayPrincipal(
            botId: call.principal.botId, sessionId: record.sessionId, kind: .task, expiresAt: Int64.max)
        _ = try await eventWriter.append(
            type: "task.stop_requested", principal: principal, data: record.jsonValue,
            eventId: "stop:\(record.taskId)")
        _ = try await eventWriter.append(
            type: "task.settled", principal: principal, data: record.jsonValue,
            eventId: "settled:\(record.taskId)")
        return .success(record.jsonValue)
    }

    private func updateRoutine(_ arguments: BotJSONValue, call: BotResolvedToolCall) async throws -> BotMCPCallResult {
        var authority = turnAuthority(for: call)
        let assessment = try await RoutineAuthority.assess(
            arguments: arguments, machine: routineMachine,
            botId: call.principal.botId, now: now())
        if assessment.requiresConfirmation, !authority.isUserTurn,
           authority.approvalID == nil {
            let effect = BotToolEffect(
                tool: "UpdateRoutine", operation: "routine.authorize",
                resource: assessment.resource, target: assessment.resource,
                mutability: .write, policy: .ask,
                label: "确认更新例行工作",
                detail: "\(authority.approvalSourceDescription)；\(assessment.detail)",
                known: false, isMcp: true)
            let outcome = await approvals.request(
                call: call, effects: [effect], action: "UpdateRoutine",
                detail: assessment.detail, command: "", alwaysScope: "none",
                persistence: approvalPersistence(for: call), origin: "structural")
            guard outcome.allowed else {
                return .failure(
                    "permission_denied",
                    outcome.pending
                        ? "审批还在等待用户确认；任务已经停下，用户决定后会继续"
                        : outcome.message ?? "routine change requires user confirmation in this turn")
            }
            authority.approvalID = outcome.approvalId
        }
        let result = try await BotRoutineTool.handle(
            machine: routineMachine, principal: call.principal, arguments: arguments,
            now: now(), authority: authority)
        guard case .object(let args) = arguments, case .string(let action)? = args["action"] else {
            throw BotMCPError.invalidRequest("更新例行任务需要指定动作")
        }
        if !["get", "list"].contains(action) {
            let type = action == "create" ? "routine.defined" : action == "delete" ? "routine.deleted" : "routine.updated"
            _ = try await eventWriter.append(type: type, principal: call.principal, data: result)
        }
        return .success(result)
    }

    private func requestApproval(_ arguments: BotJSONValue, call: BotResolvedToolCall) async throws -> BotMCPCallResult {
        guard case .object(let args) = arguments, let action = string(args["action"]), !action.isEmpty else {
            throw BotMCPError.invalidRequest("请求审批需要说明要申请什么")
        }
        let detail = string(args["detail"]) ?? ""
        let command = string(args["command"]) ?? ""
        let resource = BotResourceNormalizer.normalize("action=\(action)")
        var effects = command.isEmpty ? [] : BotApprovalPatternAnalyzer.effects(
            tool: "bash", arguments: .object(["command": .string(command)]),
            workspace: BotWorkspaceLayout.botRoot(botId: call.principal.botId))
        effects.append(BotToolEffect(
            tool: "RequestApproval", operation: "approval.weak-action", resource: resource,
            target: command.isEmpty ? resource : command, mutability: .destructive, policy: .ask,
            label: action, detail: detail, known: false, isMcp: true))
        let alwaysScope = effects.contains(where: \.known) ? "until" : "session"
        let outcome = await approvals.request(
            call: call, effects: effects, action: action, detail: detail,
            command: command, alwaysScope: alwaysScope,
            persistence: approvalPersistence(for: call), origin: "structural")
        var result: [String: BotJSONValue] = [
            "allowed": .bool(outcome.allowed), "decision": .string(outcome.allowed ? "allowed" : "denied"),
            "approvalId": outcome.approvalId.map(BotJSONValue.string) ?? .null,
            "message": outcome.message.map(BotJSONValue.string) ?? .null,
            "pending": .bool(outcome.pending),
        ]
        if let expiresAt = outcome.expiresAt {
            result["expiresAt"] = .number(Double(expiresAt))
        }
        // The card receipt must describe the real grant. Keep the legacy
        // allowed/denied decision above for the model and add the explicit
        // user decision + effective scope for the row projection.
        if let decision = outcome.decision {
            result["approvalDecision"] = .string(decision.rawValue)
        }
        if let scope = outcome.scope {
            result["scope"] = .string(scope)
        }
        // The model sees this text as the tool result and tends to repeat it
        // verbatim. Lead with the human outcome and keep the structured fields
        // after it, so a plain-language reply never has to quote `allowed`,
        // `decision`, `scope`, an approval id or an English enum. The
        // structured content is unchanged for the card/row projection.
        let value = BotJSONValue.object(result)
        let encoded = (try? value.encoded()).map { String(decoding: $0, as: UTF8.self) } ?? "{}"
        return .success(value, text: Self.approvalResultSummary(outcome) + "\n" + encoded)
    }

    /// One plain Chinese sentence for the model-facing approval result. It
    /// mirrors the receipt wording the user saw, without ids or enum names.
    private static func approvalResultSummary(_ outcome: BotApprovalOutcome) -> String {
        if outcome.pending {
            return "审批请求已经发出，正在等用户确认。"
        }
        guard outcome.allowed else {
            return "这次请求没有获得允许，已经停止。"
        }
        switch (outcome.decision, outcome.scope) {
        case (.some(.always), .some("session")):
            return "用户已允许，本次对话内都有效。"
        case (.some(.always), .some("until")):
            return "用户已总是允许，之后同类操作不必再问。"
        case (.some(.allowOnce), _):
            return "用户已允许这一次，可以继续。"
        default:
            return "用户已允许，可以继续。"
        }
    }

    private func sendToUser(_ arguments: BotJSONValue, call: BotResolvedToolCall) async throws -> BotMCPCallResult {
        guard call.principal.kind == .chat else { throw BotMCPError.invalidRequest("只有主聊天可以主动发消息") }
        guard !hiddenTextSessions.contains(call.sessionId), !suppressingTextSessions.contains(call.sessionId) else {
            throw BotMCPError.invalidRequest("这一回合的正文输出已被卡片收尾")
        }
        guard case .object(let args) = arguments, let message = string(args["message"]), !message.isEmpty else {
            throw BotMCPError.invalidRequest("主动发消息需要提供内容")
        }
        let rowId = "message-\(UUID().uuidString.lowercased())"
        _ = try await eventWriter.append(
            type: "ui.send_to_user", principal: call.principal,
            data: .object([
                "id": .string(rowId), "type": .string("text"), "role": .string("assistant"),
                "text": .string(message), "content": .string(message),
            ]))
        return .success(.object(["ok": .bool(true), "rowId": .string(rowId)]))
    }

    private func effectsForApproval(name: String, botID: String,
                                    arguments: BotJSONValue) async -> [BotToolEffect] {
        if name == BotToolCatalog.volatileContextName { return [] }
        let workspace = BotWorkspaceLayout.botRoot(botId: botID)
        if name == "bash" {
            return BotApprovalPatternAnalyzer.effects(
                tool: name, arguments: arguments, workspace: workspace)
        }
        if name == "write" || name == "edit" {
            // Inside the Bot workspace root the DSH file sandbox is the
            // boundary and no Bot approval card is needed. Outside it the
            // effect is the directory-granular `file.write`/`file.edit`.
            return BotEgressEffects.fileEffects(
                tool: name, arguments: arguments, workspaceRoot: workspace)
        }
        let effect = BotToolEffectClassifier.effect(for: name, arguments: arguments)
        return effect.mutability == .read || effect.ui || effect.policy == .auto ? [] : [effect]
    }

    private func taskResult(_ value: BotJSONValue,
                            authorization: BotTaskAuthorization) -> BotJSONValue {
        guard case .object(var fields) = value else { return value }
        fields["authorization"] = authorization.jsonValue
        return .object(fields)
    }

    /// Deny a task session's write before it reaches the user as an approval
    /// card. The subset is derived from the session capabilities issued at
    /// task creation, so a model-supplied argument cannot widen it.
    private func taskAuthorityDenial(call: BotResolvedToolCall, name: String,
                                     arguments: BotJSONValue, command: String) -> String? {
        guard call.principal.kind == .task else { return nil }
        if name == BotToolCatalog.attachToModelName {
            // A background task has no present user to approve model egress;
            // keep the image in the workspace and let the parent chat decide.
            return "task_scope:model_image_denied"
        }
        guard name == "write" || name == "edit" || name == "bash" else { return nil }
        guard let authorization = BotTaskAuthorization.from(
            capabilities: call.principal.capabilities) else {
            return "task_scope:missing_authorization"
        }
        if name == "write" || name == "edit" {
            let path = firstNonEmpty(arguments["file_path"], arguments["path"])
            guard let path else { return nil }
            return authorization.allowsWrite(to: path) ? nil : "task_scope:path_denied"
        }
        if name == "bash" {
            return bashWriteDenial(command: command, authorization: authorization)
        }
        return nil
    }

    /// Conservative write-target extraction for a task child's bash. Redirect
    /// targets and the target operands of common write commands are checked;
    /// opaque interpreter writes are a documented remaining gap. A read that
    /// only names an outside path is not denied.
    private func bashWriteDenial(command: String,
                                 authorization: BotTaskAuthorization) -> String? {
        guard !command.isEmpty else { return nil }
        let targets = ShellWriteTargets.targets(in: command)
        for target in targets where !authorization.allowsWrite(to: target) {
            return "task_scope:path_denied"
        }
        return nil
    }

    private func encode<T: Encodable>(_ value: T) throws -> BotJSONValue {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return try BotJSONValue.parse(encoder.encode(value))
    }

    private func firstNonEmpty(_ values: BotJSONValue?...) -> String? {
        for value in values {
            if let text = string(value), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return text }
        }
        return nil
    }

    private func string(_ value: BotJSONValue?) -> String? {
        guard case .string(let text)? = value else { return nil }
        return text
    }

    private func bool(_ value: BotJSONValue?) -> Bool? {
        guard case .bool(let flag)? = value else { return nil }
        return flag
    }

    private func optionalInt(_ value: BotJSONValue?) throws -> Int? {
        guard let value else { return nil }
        guard case .number(let number) = value, number.isFinite, number.rounded() == number else {
            throw BotMCPError.invalidRequest("timeout/limit must be an integer")
        }
        return Int(number)
    }

    private func bareToolName(_ name: String) -> String {
        guard name.hasPrefix("mcp__") else { return name }
        return name.components(separatedBy: "__").last ?? name
    }

    private func key(_ runtimeId: String, _ sessionId: String, _ callId: String) -> String {
        "\(runtimeId)\u{0}\(sessionId)\u{0}\(callId)"
    }

    private static func code(_ error: BotMCPError) -> String {
        switch error {
        case .invalidRequest: return "invalid_arguments"
        case .unauthorized: return "unauthorized"
        case .unknownTool: return "unknown_tool"
        case .unattributed: return "unattributed"
        case .crossSessionDenied: return "cross_session_read_denied"
        case .timeout: return "timeout"
        case .unavailable: return "unavailable"
        }
    }

    private static func message(_ error: BotMCPError) -> String {
        switch error {
        case .invalidRequest(let message), .unavailable(let message): return message
        case .unauthorized: return "Unauthorized"
        case .unknownTool(let name): return "未知工具：\(name)"
        case .unattributed: return "这次调用无法归属到会话"
        case .crossSessionDenied: return "请求的会话不属于当前调用方"
        case .timeout: return "操作超时了"
        }
    }
