/// Where the App keeps the packed Worker assets.
///
/// The loopback origin serves the directory as `/` + `/static/*`, the image as
/// `/image/base`, and lazy shards as `/image/lazy/<sha256>.tar.gz`. `overlay`
/// files are generated by the workspace log into the workspace root.
public struct PhoneDSHBundleLocation: Equatable, Sendable {
    /// Directory containing `index.html`, `boot.js`, `worker-entry.js` and
    /// `client.js` (served by the loopback origin). The bootstrap page loads
    /// the Worker entry relative to itself.
    public var staticDirectory: URL
    /// The packed Worker entry (`worker-entry.js`), normally inside
    /// ``staticDirectory``. It is informational for the engine boot URL.
    public var workerEntry: URL
    /// `image.tar.gz` served at `/image/base`.
    public var imageArchive: URL
    /// Directory holding `lazy/<sha256>.tar.gz` shards (PLAN §2.3).
    public var lazyDirectory: URL

    /// Builds a bundle description. The three derived URLs default to the
    /// conventional names under `staticDirectory` / the workspace root.
    public init(staticDirectory: URL,
                workerEntry: URL? = nil,
                imageArchive: URL? = nil,
                lazyDirectory: URL? = nil) {
        self.staticDirectory = staticDirectory
        self.workerEntry = workerEntry
            ?? staticDirectory.appendingPathComponent("worker-entry.js")
        self.imageArchive = imageArchive
            ?? staticDirectory.appendingPathComponent("image.tar.gz")
        self.lazyDirectory = lazyDirectory
            ?? staticDirectory.appendingPathComponent("lazy", isDirectory: true)
    }

    /// Whether every location exists on disk.
    public func exists(fileManager: FileManager = .default) -> Bool {
        var isDirectory: ObjCBool = false
        return fileManager.fileExists(atPath: staticDirectory.path,
                                      isDirectory: &isDirectory)
            && isDirectory.boolValue
            && fileManager.fileExists(atPath: workerEntry.path)
            && fileManager.fileExists(atPath: imageArchive.path)
            && fileManager.fileExists(atPath: lazyDirectory.path,
                                      isDirectory: &isDirectory)
            && isDirectory.boolValue
    }
}

/// Names of the Worker environment the host injects into the engine boot
/// (D24). The App no longer has to set them in
/// ``PhoneDSHConfiguration/engine``; values the App does put there still win.
public enum PhoneDSHWorkerEnvironment {
    /// Per-start launch token the resident phone surface consumes.
    public static let launchToken = "PDSH_DSH_LAUNCH_TOKEN"
    /// Ordered-channel WebSocket URL (`ws://127.0.0.1:<port>/channel`).
    public static let channelURL = "PDSH_CHANNEL_URL"
    /// Per-start bearer the Worker presents on the ordered channel.
    public static let channelToken = "PDSH_CHANNEL_TOKEN"
    /// Loopback origin that carries the model gateway at `/v1/http`
    /// (`llm-bridge` derives its proxy route from this value).
    public static let gatewayURL = "PDSH_CHANNEL_ORIGIN"
    /// Decimal bytes of the host's single-file budget. The Worker entry uses
    /// it for write pre-checks and the ENG-05 capability manifest.
    public static let singleFileLimit = "PDSH_SINGLE_FILE_LIMIT_BYTES"
    /// Decimal bytes of the host's WASI hot-instance budget for tool workers
    /// (the tier's `wasiHotInstanceBytes`). The Worker entry uses it for the
    /// toolbox memory ceiling and the ENG-05 capability manifest.
    public static let wasiHotInstanceBytes = "PDSH_WASI_HOT_INSTANCE_BYTES"
    /// The host's VFS tier quotas, so the capability manifest publishes the
    /// same numbers the write path enforces (one source: `BudgetTable`).
    public static let vfsLogicalBytes = "PDSH_VFS_LOGICAL_BYTES"
    public static let vfsWorkspaceBytes = "PDSH_VFS_WORKSPACE_BYTES"
    public static let vfsSessionsBytes = "PDSH_VFS_SESSIONS_BYTES"
    public static let vfsTmpBytes = "PDSH_VFS_TMP_BYTES"
    /// Comma-separated hosts the Worker may reach through `/v1/http` egress
    /// (``PhoneDSHConfiguration/egressAllowHosts``, wildcards included). The
    /// Worker entry only states it in the capability manifest so the agent
    /// knows what `curl` can reach; the gateway enforces the list.
    public static let egressAllow = "PDSH_EGRESS_ALLOW"
}

/// Configuration of the App-process DSH host.
public struct PhoneDSHConfiguration: Equatable, Sendable {
    /// Default event-silence threshold for a turn (G2-FIX-12).
    ///
    /// Five minutes leaves room for a slow first token and a long tool run
    /// while still surfacing a stall before the 10-minute scenario budget.
    /// The App overrides it through ``turnInactivityTimeout``.
    public static let defaultTurnInactivityTimeout: TimeInterval = 300

    /// Workspace root, `Library/xl/<workspace_id>/` (PLAN §2.3).
    public var workspaceRoot: URL
    /// Budget tier; PLAN §2.5 defaults to the 8 GB row.
    public var deviceTier: DeviceTier
    /// Loopback listener configuration (host is always `127.0.0.1`).
    public var loopback: LoopbackConfiguration
    /// Workspace WAL and journal configuration (PLAN §2.3).
    public var log: WorkspaceLogConfiguration
    /// Model gateway configuration. Its allow-list is always
    /// ``allowedModelHosts`` ∪ ``egressAllowHosts`` at start time (see
    /// ``resolvedGatewayConfiguration()``); a caller that mutates this value
    /// widens the same union rather than replacing it.
    public var gateway: ModelGatewayConfiguration
    /// WKWebView boot configuration; the host replaces origin/token/boot id at
    /// runtime with the values of the actually bound loopback listener.
    ///
    /// The host also injects the D24 Worker environment
    /// (``PhoneDSHWorkerEnvironment``) derived from the bound listener. An
    /// entry the App sets in ``WebEngineConfiguration/environment`` overrides
    /// the injected value of the same name.
    public var engine: WebEngineConfiguration
    /// Read-only accelerator provider used when ``execProvider`` is `nil`.
    public var accelerators: PDSHShellProvider
    /// Read-only accelerator provider; overrides ``accelerators`` when set.
    public var execProvider: (any ExecProvider)?
    /// Names advertised in the host HELLO caps as `accelerator:<name>`.
    ///
    /// An empty list advertises none; the W4 pdsh-shell build fills both this
    /// list and ``execProvider`` together.
    public var acceleratorNames: [String]
    /// Budget override (PLAN §2.5). Defaults to the row for ``deviceTier``.
    /// The workspace bucket, VFS logical cap and engine heap are grown when
    /// needed so the single-file budget is always reachable.
    public var budgets: BudgetTable
    /// Largest logical file the Worker may publish, in bytes.
    ///
    /// The tier default is 64 / 48 / 32 / 16 MiB for the 8 / 6 / 4 / ≤3 GiB
    /// rows. The host may configure any value in
    /// ``BudgetTable/minimumSingleFileLimitBytes``...``BudgetTable/absoluteMaximumSingleFileBytes``;
    /// values are clamped and the 4 GiB and ≤3 GiB tiers keep their smaller
    /// gate. The value is also injected to the Worker as
    /// ``PhoneDSHWorkerEnvironment/singleFileLimit`` so the capability manifest
    /// can state it.
    public var singleFileLimitBytes: Int
    /// Packed Worker assets. `nil` means the host refuses to start until the
    /// App supplies the real bundle.
    public var bundle: PhoneDSHBundleLocation?
    /// Upstream hosts the model provider traffic may connect to. Empty denies
    /// all model hosts. This allow-list does not by itself enable POST retries.
    public var allowedModelHosts: Set<String>
    /// Additional hosts the Worker may reach through `/v1/http` egress
    /// (ENG-04). The scenario runner fills this from `scenario.json`
    /// `network.allow`; an App supplies the same field from its settings.
    ///
    /// The gateway allow-list is the union of ``allowedModelHosts`` and this
    /// set, so a model host never has to be repeated here. The credential
    /// provider is still asked per host, so admitting an egress host does not
    /// hand it a model credential by itself. An empty set admits no extra
    /// host.
    public var egressAllowHosts: Set<String>
    /// Exact model endpoint URLs whose POSTs may be replayed after a 429/5xx
    /// or a transport failure before response headers. Each entry is matched
    /// by scheme, host, effective port and path. Configure only endpoints
    /// whose upstream contract makes replay safe; `Idempotency-Key` alone is
    /// not evidence of that contract. Empty disables automatic POST retries.
    public var replaySafeModelEndpoints: Set<String>
    /// Remote DSH host used by ``PhoneDSHHost/beginHandoff()`` and
    /// ``PhoneDSHHost/reclaim()``. `nil` disables the remote path on this host:
    /// the local lifecycle still works and `beginHandoff()` fails loud with
    /// ``PhoneDSHError/unsupported(_:)``. The endpoint must be `https` and must
    /// not carry URL userinfo, a query or a fragment (the remote credential is
    /// an `Authorization` header); a base path is allowed. The credential
    /// service is resolved through ``credentialProvider``.
    public var handoff: HandoffClientConfiguration?
    /// Credential provider for the model gateway and the remote DSH handoff
    /// Bearer (never exposed to the Worker).
    public let credentialProvider: any CredentialProvider
    /// Additional exact-origin/path egress admission applied by the gateway
    /// after its static host union. The App supplies the MCP access policy;
    /// `nil` keeps the previous host-only behavior.
    public var egressAuthorizer: (any EgressHostAuthorizing)?
    /// Loopback MCP server the Worker reaches through `/mcp*` (PLAN §2.1).
    public var mcpLoopbackURL: URL?
    /// Maximum continuous uptime before a planned restart (24 h). Pressure and
    /// a WebContent death trigger earlier; see `RestartPolicy`. The
    /// W2 controller owns the scheduler; the facade exposes the flag for the
    /// App's settings screen.
    public var plannedRestartInterval: TimeInterval
    /// `Running -> Draining` deadline in seconds (PLAN §2.5: 20 s).
    public var drainDeadline: TimeInterval
    /// How long ``PhoneDSHHost/start()`` waits for the Worker HELLO.
    public var helloTimeout: TimeInterval
    /// How long the session event stream of an open turn may stay silent
    /// before the host aborts the turn (G2-FIX-12).
    ///
    /// The watchdog measures event silence, not turn duration: every session
    /// event (usage, streaming delta, tool event, progress, status) renews the
    /// timer. When the threshold expires the host publishes a terminal
    /// `.turnEnded(..., reason: .failed)` carrying the last event kind and the
    /// measured silence, cancels the turn and records the stall in
    /// ``PhoneDSHDiagnostics``. Validated by
    /// ``PhoneDSHHost/start()``: it must be a positive finite number of
    /// seconds. The default leaves room for a slow first token and a long tool
    /// run while still surfacing a stall inside the scenario wall budget.
    public var turnInactivityTimeout: TimeInterval

    /// Identity of the credential provider used by ``Equatable``; provider
    /// instances are not value-comparable.
    private let credentialProviderIdentity: String
    private let execProviderIdentity: String
    private let egressAuthorizerIdentity: String

    /// The provider endpoints under `baseURL` that a host should pass as
    /// `replaySafeModelEndpoints` (see
    /// ``ModelGatewayConfiguration/standardModelEndpoints(baseURL:)``).
    public static func standardModelEndpoints(baseURL: URL) -> Set<String> {
        ModelGatewayConfiguration.standardModelEndpoints(baseURL: baseURL)
    }

    /// Builds the host configuration.
    ///
    /// - Parameters:
    ///   - workspaceRoot: `Library/xl/<workspace_id>/` (PLAN §2.3).
    ///   - token: Per-start loopback bearer token; only the App and the
    ///     loopback origin ever see it.
    ///   - origin: Public origin the App reports to UI code before the actual
    ///     listener port is known; the host replaces it with the bound one.
    ///   - deviceTier: Budget row when `budgets` is `nil`.
    ///   - bundle: Packed Worker assets; `nil` makes ``PhoneDSHHost/start()``
    ///     fail with ``PhoneDSHError/invalidBundle(_:)``.
    ///   - allowedModelHosts: Upstream hosts for model-provider traffic; the
    ///     gateway allow-list always also contains `egressAllowHosts`.
    ///   - egressAllowHosts: Extra hosts Worker `/v1/http` egress may reach
    ///     (scenario `network.allow` / App settings).
    ///   - replaySafeModelEndpoints: Exact model endpoint URLs whose POST
    ///     requests may be retried. Empty disables POST retries by default.
    ///   - handoff: Remote DSH endpoint and credential service for
    ///     `beginHandoff()`/`reclaim()`; `nil` keeps the host local-only. The
    ///     endpoint must use `https`.
    ///   - credentialProvider: Host-side model and remote-DSH credentials;
    ///     never sent to the Worker.
    ///   - execProvider: Read-only accelerator process launcher. `nil` uses
    ///     the bundled ``PhoneDSHShell/PDSHShellProvider``.
    ///   - acceleratorNames: Commands advertised as `accelerator:<name>` in the
    ///     host HELLO caps.
    ///   - mcpLoopbackURL: Loopback MCP server reached through `/mcp*`.
    ///   - budgets: Budget override; defaults to the row of `deviceTier`.
    ///   - singleFileLimitBytes: Host single-file budget; defaults to the
    ///     row's value and is clamped to the tier gate.
    ///   - plannedRestartInterval: WebContent restart interval (PLAN §2.5).
    ///   - drainDeadline: `Running -> Draining` deadline (PLAN §2.5).
    ///   - helloTimeout: How long `start()` waits for the Worker HELLO.
    ///   - turnInactivityTimeout: Event-silence threshold of an open turn
    ///     (G2-FIX-12); must be a positive finite number of seconds.
    public init(workspaceRoot: URL, token: String, origin: URL,
                deviceTier: DeviceTier = DeviceTier.default,
                bundle: PhoneDSHBundleLocation? = nil,
                allowedModelHosts: Set<String> = [],
                egressAllowHosts: Set<String> = [],
                replaySafeModelEndpoints: Set<String> = [],
                handoff: HandoffClientConfiguration? = nil,
                credentialProvider: any CredentialProvider = StaticCredentialProvider([:]),
                egressAuthorizer: (any EgressHostAuthorizing)? = nil,
                execProvider: (any ExecProvider)? = nil,
                acceleratorNames: [String] = [],
                mcpLoopbackURL: URL? = nil,
                budgets: BudgetTable? = nil,
                plannedRestartInterval: TimeInterval? = nil,
                drainDeadline: TimeInterval? = nil,
                helloTimeout: TimeInterval = 60,
                turnInactivityTimeout: TimeInterval =
                    PhoneDSHConfiguration.defaultTurnInactivityTimeout,
                singleFileLimitBytes: Int? = nil) {
        let baseBudgets = budgets ?? BudgetTable.table(for: deviceTier)
        // An explicit override is clamped to the tier gate and grows the
        // buckets only when needed. A caller-supplied row with no override is
        // used as-is so test doubles and App tunings keep their intent.
        let resolvedBudgets = singleFileLimitBytes.map(baseBudgets.withSingleFileLimit)
            ?? baseBudgets
        self.workspaceRoot = workspaceRoot
        self.deviceTier = deviceTier
        self.loopback = LoopbackConfiguration(token: token)
        self.log = WorkspaceLogConfiguration(
            root: workspaceRoot,
            singleFileLimitBytes: resolvedBudgets.singleFileBytes)
        self.gateway = ModelGatewayConfiguration(
            allowedUpstreamHosts: ModelGatewayConfiguration.effectiveAllowedUpstreamHosts(
                modelHosts: allowedModelHosts,
                egressAllowHosts: egressAllowHosts))
        self.engine = WebEngineConfiguration(origin: origin, token: token)
        self.accelerators = PDSHShellProvider()
        self.execProvider = execProvider
        self.acceleratorNames = acceleratorNames
        self.budgets = resolvedBudgets
        self.singleFileLimitBytes = resolvedBudgets.singleFileBytes
        self.bundle = bundle
        self.allowedModelHosts = allowedModelHosts
        self.egressAllowHosts = egressAllowHosts
        self.replaySafeModelEndpoints = replaySafeModelEndpoints
        self.handoff = handoff
        self.credentialProvider = credentialProvider
        self.egressAuthorizer = egressAuthorizer
        self.mcpLoopbackURL = mcpLoopbackURL
        self.plannedRestartInterval = plannedRestartInterval
            ?? TimeInterval(resolvedBudgets.plannedRestartIntervalSeconds)
        self.drainDeadline = drainDeadline ?? HostStateMachine.drainDeadlineSeconds
        self.helloTimeout = max(1, helloTimeout)
        // Left exactly as configured so ``validateForStart()`` can reject an
        // unusable value instead of silently clamping it.
        self.turnInactivityTimeout = turnInactivityTimeout
        self.credentialProviderIdentity = Self.identity(of: credentialProvider)
        self.execProviderIdentity = execProvider.map(Self.identity(of:)) ?? "none"
        self.egressAuthorizerIdentity = egressAuthorizer.map(Self.identity(of:)) ?? "none"
    }

    /// The model-gateway configuration for one start: the explicit
    /// ``gateway`` allow-list ∪ ``allowedModelHosts`` ∪ ``egressAllowHosts``.
    ///
    /// Unioning (instead of overwriting) keeps every caller that widens
    /// ``gateway`` directly working, while the canonical Worker-egress wiring
    /// is now ``egressAllowHosts`` (ENG-04). A caller cannot accidentally
    /// narrow the allow-list by setting only one of the fields.
    public func resolvedGatewayConfiguration() -> ModelGatewayConfiguration {
        var resolved = gateway
        // The allow-list and replay policy are separate. Only exact endpoint
        // URLs supplied by the host can opt a POST into automatic retries.
        resolved.replaySafeModelEndpoints.formUnion(replaySafeModelEndpoints)
        resolved.allowedUpstreamHosts = ModelGatewayConfiguration.effectiveAllowedUpstreamHosts(
            modelHosts: gateway.allowedUpstreamHosts.union(allowedModelHosts),
            egressAllowHosts: egressAllowHosts)
        return resolved
    }

    public static func == (lhs: PhoneDSHConfiguration, rhs: PhoneDSHConfiguration) -> Bool {
        lhs.workspaceRoot == rhs.workspaceRoot
            && lhs.deviceTier == rhs.deviceTier
            && lhs.loopback == rhs.loopback
            && lhs.log == rhs.log
            && lhs.gateway == rhs.gateway
            && lhs.engine == rhs.engine
            && lhs.accelerators == rhs.accelerators
            && lhs.acceleratorNames == rhs.acceleratorNames
            && lhs.budgets == rhs.budgets
            && lhs.singleFileLimitBytes == rhs.singleFileLimitBytes
            && lhs.bundle == rhs.bundle
            && lhs.allowedModelHosts == rhs.allowedModelHosts
            && lhs.egressAllowHosts == rhs.egressAllowHosts
            && lhs.replaySafeModelEndpoints == rhs.replaySafeModelEndpoints
            && lhs.handoff == rhs.handoff
            && lhs.mcpLoopbackURL == rhs.mcpLoopbackURL
            && lhs.plannedRestartInterval == rhs.plannedRestartInterval
            && lhs.drainDeadline == rhs.drainDeadline
            && lhs.helloTimeout == rhs.helloTimeout
            && lhs.turnInactivityTimeout == rhs.turnInactivityTimeout
            && lhs.credentialProviderIdentity == rhs.credentialProviderIdentity
            && lhs.execProviderIdentity == rhs.execProviderIdentity
            && lhs.egressAuthorizerIdentity == rhs.egressAuthorizerIdentity
    }

    private static func identity<T>(of value: T) -> String {
        if Mirror(reflecting: value).displayStyle == .class {
            return "object:" + String(describing: ObjectIdentifier(value as AnyObject))
        }
        return "value:" + String(reflecting: T.self)
    }
}

/// Facade state. It stays coarser than `HostState` on purpose: the App target
/// reacts to a handful of states, while the controller owns the nine-state
/// machine of PLAN §2.5.
public enum PhoneDSHState: String, CaseIterable, Codable, Sendable {
    /// No host is attached to the App process.
    case stopped
    /// Recovery and WebContent boot are in progress; admission is closed.
    case starting
    /// Admission is open and the worker is connected.
    case running
    /// Draining for background, restart or handoff.
    case draining
    /// The workspace runs on a remote host.
    case remote
    /// Fail loud: the App must surface the error and wait for the user;
    /// ``PhoneDSHHosting/userReset()`` (or its alias `reset()`) is the only
    /// exit out of this state.
    case failed
}

/// Host-facing entry point of the facade (PLAN §2.1).
///
/// Attach visibility requirement (`PLAN §2.5`): `start()` boots the WKWebView
/// through `WebEngineControlling`, which requires a window-attached visible
/// area of at least one point; the facade must not report `running` until the
/// engine confirms that attachment.
public protocol PhoneDSHHosting: Sendable {
    /// Current facade state.
    var state: PhoneDSHState { get async }
    /// Opens the workspace, recovers the WAL, boots the worker and opens
    /// admission. Idempotent while starting or running. A host restored in
    /// `Backoff` starts only after its D24 retry deadline.
    func start() async throws
    /// Drains in-flight work, closes the epoch, parks the worker and stops the
    /// loopback listener.
    func stop() async throws
    /// Clears a fail-loud state after the user acknowledged it (D14
    /// `Failed -> Recovering`) and boots the host again. A failed host never
    /// recovers on its own; ``start()`` keeps throwing
    /// ``PhoneDSHError/hostFailed(_:)`` until this method is called.
    func reset() async throws
    /// D24 name of the explicit user reset. Same operation as
    /// ``PhoneDSHHosting/reset()``; the failed-state guard is identical.
    func userReset() async throws
    /// D24: the D14 `Running -> Recovering -> Running` planned restart. Closes
    /// admission, drains in-flight `0x40` requests for at most the 20 s
    /// window, rebuilds the overlay and the Worker, waits for HELLO, and
    /// reopens admission.
    func plannedRestart(reason: String) async throws
    /// D15: closes admission, closes the WAL epoch and replicates the workspace
    /// to the configured remote DSH host (`Running -> HandingOff -> Remote`).
    /// The local Worker/loopback is stopped before the snapshot so it cannot
    /// produce a mutation above the replicated watermark. Requires a running
    /// local host and ``PhoneDSHConfiguration/handoff``.
    func beginHandoff() async throws -> HandoffCompletion
    /// D15: returns the remote workspace to this phone
    /// (`Remote -> Reclaiming -> Recovering -> Running`). Applies the returned
    /// WAL segments, installs the new phone fence, boots the local Worker and
    /// only then reopens admission after the lease check. Works on a fresh host
    /// instance when the App injected a secure ``HandoffReclaimTokenStore``.
    func reclaim() async throws -> HandoffReclaimOutcome
    /// Cold/explicit reclaim with the complete credential the App recovered
    /// from its own secure vault. The non-secret workspace/endpoint/remote
    /// fence binding is checked before any request; the remote's `200` proves a
    /// previously uncertain CAS before any local fence is recorded. The token
    /// is never read from the workspace, a URL, the channel or a log.
    func reclaim(using credential: HandoffReclaimToken) async throws
        -> HandoffReclaimOutcome
    /// Cold/explicit reclaim with a bare token. It is accepted only when the
    /// injected secure store already holds the exact bound credential.
    /// Otherwise use ``reclaim(using:)`` with the saved
    /// ``HandoffReclaimToken``; a bare token has no workspace/endpoint
    /// binding to check before applying returned segments.
    func reclaim(usingRemoteToken token: String) async throws -> HandoffReclaimOutcome
    /// Reports the latest WebContent heap sample (`nil` clears it). The budget
    /// monitor applies the same clear-tmp -> planned-restart -> handoff actions
    /// to heap pressure as to VFS pressure.
    func reportEngineHeapBytes(_ bytes: Int?) async
    /// Snapshot for the App's diagnostics screen and for bug reports; contains
    /// no tokens or credentials.
    func diagnostics() async -> PhoneDSHDiagnostics
}

/// Errors the facade reports before or after a host state transition.
public enum PhoneDSHError: Error, Equatable, Sendable {
    /// The host has not been started yet.
    case notStarted
    /// A local DSH harness needs a JIT-enabled WebContent process.
    case lockdownMode
    /// The host state machine or the App operation does not allow this call.
    case invalidState(String)
    /// The WKWebView is not attached to a window with one visible point.
    case engineNotAttached
    /// The packed Worker assets are missing or unusable.
    case invalidBundle(String)
    /// The Worker did not send HELLO before the deadline.
    case startTimedOut(String)
    /// A configuration value is unusable; the host refuses to start.
    case invalidConfiguration(String)
    /// The fence/lease presented by the Worker is not the host's authority.
    case leaseRejected(String)
    /// The ordered channel is not connected.
    case channelUnavailable
    /// A response violated the remote API envelope.
    case invalidResponse(String)
    /// The host is in the fail-loud state; the user must reset it.
    case hostFailed(String)
    /// D24: a host restored in `Backoff` was asked to start before its
    /// persisted retry deadline. The date is the earliest allowed start.
    case backoffNotElapsed(Date)
    /// A feature is not available on this build.
    case unsupported(String)
}

extension PhoneDSHError: CustomStringConvertible {
    public var description: String {
        switch self {
        case .notStarted:
            return "the phone DSH host is not started"
        case .lockdownMode:
            return "the local DSH harness is unavailable while Lockdown Mode is on"
        case .invalidState(let detail):
            return "the host state does not allow this operation: \(detail)"
        case .engineNotAttached:
            return "the web engine must be attached to a window with at least one visible point"
        case .invalidBundle(let detail):
            return "the Worker bundle is unusable: \(detail)"
        case .startTimedOut(let detail):
            return "the Worker did not become ready in time: \(detail)"
        case .invalidConfiguration(let detail):
            return "invalid PhoneDSHConfiguration: \(detail)"
        case .leaseRejected(let detail):
            return "the Worker presented a stale lease: \(detail)"
        case .channelUnavailable:
            return "the ordered channel is not connected"
        case .invalidResponse(let detail):
            return "invalid remote API response: \(detail)"
        case .hostFailed(let detail):
            return "the phone DSH host failed: \(detail)"
        case .backoffNotElapsed(let deadline):
            return "the phone DSH host is in Backoff until \(deadline.timeIntervalSince1970)"
        case .unsupported(let detail):
            return "unsupported operation: \(detail)"
        }
    }
}

/// Budget limits versus current usage (PLAN §2.5, budgets.md §4).
public struct PhoneDSHBudgetSnapshot: Equatable, Sendable {
    /// The tier row in force for this boot.
    public var table: BudgetTable
    /// `/dsh/workspace/**` plus `/dsh/home/**` (the VFS logical bytes).
    public var vfsLogicalBytesUsed: Int
    /// Bytes materialized under `/dsh/workspace/**`.
    public var workspaceBytesUsed: Int
    /// Bytes materialized under `/dsh/home/sessions/**`.
    public var sessionBytesUsed: Int
    /// Volatile `/dsh/tmp/**`, always 0 because it is never materialized.
    public var tmpBytesUsed: Int
    /// Bytes occupied by WAL segments.
    public var walBytesUsed: Int
    /// Bytes occupied by the journal store.
    public var journalBytesUsed: Int
    /// Bytes occupied by the model-gateway response log.
    public var responseLogBytesUsed: Int
    /// WebContent process terminations observed by this boot.
    public var webContentTerminations: UInt64
    /// Last reported WebContent heap occupancy, when the engine has one.
    public var engineHeapBytesUsed: Int?
    /// The action this snapshot reports: the next pending action while an
    /// episode is active, or `nil` while clear. Reading a snapshot never
    /// consumes the episode (see ``PhoneDSHHost/reportEngineHeapBytes(_:)``).
    public var lastAction: BudgetAction?
    /// Whether a hard cap was still exceeded after the actions.
    public var hardFail: Bool

    public init(table: BudgetTable,
                vfsLogicalBytesUsed: Int = 0,
                workspaceBytesUsed: Int = 0,
                sessionBytesUsed: Int = 0,
                tmpBytesUsed: Int = 0,
                walBytesUsed: Int = 0,
                journalBytesUsed: Int = 0,
                responseLogBytesUsed: Int = 0,
                webContentTerminations: UInt64 = 0,
                engineHeapBytesUsed: Int? = nil,
                lastAction: BudgetAction? = nil,
                hardFail: Bool = false) {
        self.table = table
        self.vfsLogicalBytesUsed = vfsLogicalBytesUsed
        self.workspaceBytesUsed = workspaceBytesUsed
        self.sessionBytesUsed = sessionBytesUsed
        self.tmpBytesUsed = tmpBytesUsed
        self.walBytesUsed = walBytesUsed
        self.journalBytesUsed = journalBytesUsed
        self.responseLogBytesUsed = responseLogBytesUsed
        self.webContentTerminations = webContentTerminations
        self.engineHeapBytesUsed = engineHeapBytesUsed
        self.lastAction = lastAction
        self.hardFail = hardFail
    }

    /// Remaining VFS logical bytes before the hard cap.
    public var vfsHeadroomBytes: Int {
        max(0, table.vfsLogicalBytes - vfsLogicalBytesUsed)
    }

    /// Whether the VFS logical cap is respected.
    public var isWithinVFSLimit: Bool {
        vfsLogicalBytesUsed <= table.vfsLogicalBytes
    }

    /// Whether the reported heap sample (if any) is within the tier budget.
    public var isWithinEngineHeapLimit: Bool {
        guard let engineHeapBytesUsed else { return true }
        return engineHeapBytesUsed <= table.engineHeapBytes
    }

    /// The configured single-file budget the Worker is expected to enforce.
    public var singleFileLimitBytes: Int { table.singleFileBytes }
}

/// One resource refusal recorded by the host (`ERROR VFS_REFUSED`,
/// channel.md §4.8).
///
/// A resource guard (`EFBIG`, `ENOSPC`, quota) is a bounded-phone-filesystem
/// condition, not a protocol violation: the refused mutation consumed no mseq,
/// the channel stays open, and the host records this diagnostic instead of a
/// connection error. It never moves the host state machine to Failed.
public struct PhoneDSHVFSRefusal: Equatable, Sendable {
    /// The refused VFS path.
    public var path: String
    /// Policy bound in bytes the mutation would have exceeded.
    public var limit: UInt64
    /// Resource class (`file-too-large`, `no-space`, `quota-exceeded`).
    public var reason: PhoneWireRefusalReason
    /// Human-readable detail from the Worker.
    public var message: String

    public init(path: String, limit: UInt64, reason: PhoneWireRefusalReason, message: String) {
        self.path = path
        self.limit = limit
        self.reason = reason
        self.message = message
    }

    /// Reads a validated `VFS_REFUSED` payload; nil for any other ERROR code.
    public init?(payload: ErrorPayload) {
        guard payload.isVFSRefused,
              let path = payload.path,
              let limit = payload.limit,
              let reason = payload.reason
        else { return nil }
        self.init(path: path, limit: limit, reason: reason, message: payload.message)
    }
}

