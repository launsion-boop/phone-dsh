/**
 * `cmp`: POSIX byte comparison for the Worker shell.
 *
 * The Worker command surface had no `cmp` at all, so the whole POSIX
 * byte-comparison class answered `bash: cmp: command not found` with the
 * Worker's `pdsh-shell: exit=127 program=cmp reason=not-available` trailer. The
 * G2-D04 idempotency check (`cmp -s first.md report/REPORT.md`) therefore had
 * to fall back to `sha256sum`, costing a tool round trip on every step where
 * the model wanted a yes/no answer about two files (transcript L490).
 *
 * This module adds the program to the Worker command table. It runs entirely
 * inside the Worker over the `IFileSystem` faces the shell already uses (PLAN
 * D12): two reads, no write and no host process. The implemented surface is
 * the one scripts use:
 *
 * - default: compare byte by byte and report the first difference as
 *   `<file1> <file2> differ: char <offset>, line <line>` on stdout, exit 1;
 *   identical files are silent with exit 0; a shared prefix with different
 *   lengths reports `cmp: EOF on <shorter file>` on stderr, exit 1;
 * - `-s`: silent, status only (0 equal, 1 different, 2 an operand error; the
 *   host still diagnoses a directory operand, and so does this shim);
 * - `-l`: every differing byte as `<offset> <octal1> <octal2>` (offset field
 *   width 6, byte fields width 3), then the same EOF diagnostic when the
 *   lengths differ;
 * - a missing operand is a usage error on stderr with exit 2, exactly like the
 *   host program.
 *
 * The stdout/stderr bytes and the 0/1/2 statuses mirror the host `/usr/bin/cmp`
 * this repository's corpus goldens are generated from, including the usage
 * line. That is deliberate: `cmp` is a POSIX program whose diagnostics a
 * script may parse, so they keep the host's shape instead of gaining an
 * `pdsh-shell:` trailer (the same exemption `find`/`stat` already have for the
 * built-in parser's byte-for-byte errors). The class gate in
 * `tools/shell-corpus` owns the coverage: `golden/cmp-*.jsonl` vectors are
 * generated by `tools/shell-corpus/cmp-golden.mjs` from the host program, and
 * `contract.mjs` requires the `cmp` family in the committed corpus.
 * @module @phone-dsh/dsh-shell-ext/cmp
 */

import { posix } from 'node:path'
import { defineCommand } from 'just-bash/browser'
import type { Command, ExecResult, IFileSystem } from 'just-bash/browser'

/**
 * The usage line the host program prints for a missing operand.
 *
 * It is part of the observable contract the corpus goldens pin, so it is kept
 * byte for byte (the host option set; the Worker implements `-l`/`-s`).
 */
export const CMP_USAGE = 'usage: cmp [-l | -s | -x] [-bhz] [-i num1[:num2] | --ignore-initial=num1[:num2]] [-n num | --bytes=num] file1 file2 [skip1 [skip2]]\n'

/** The comparison mode selected by the option surface. */
export type CmpMode = 'default' | 'silent' | 'long'

/** One parsed `cmp` invocation. */
export interface CmpArguments {
  /** Default first-difference report, silent status, or long byte listing. */
  readonly mode: CmpMode
  /** The two file operands in command-line order. */
  readonly operands: readonly string[]
}

/** An option word (or operand shape) the shim does not implement. */
export class CmpUsageError extends Error {
  /**
   * @param message - diagnostic body without the `cmp: ` prefix.
   */
  constructor(message: string) {
    super(message)
    this.name = 'CmpUsageError'
  }
}

/**
 * Parse `cmp`'s option surface.
 *
 * `-l` and `-s` are mutually exclusive (the host refuses the combination), and
 * an operand of `-` would name standard input, which is outside the Worker
 * surface: both fail as a usage error instead of being silently reinterpreted.
 * @param argv - arguments after the program name.
 * @returns the parsed invocation.
 * @throws {CmpUsageError} for an option outside the documented set.
 */
export function parseCmpArguments(argv: readonly string[]): CmpArguments {
  let mode: CmpMode = 'default'
  const operands: string[] = []
  let options = true
  for (const argument of argv) {
    if (!options || argument === '-' || !argument.startsWith('-')) {
      if (argument === '-') throw new CmpUsageError('standard input is not part of the Worker cmp surface')
      operands.push(argument)
      continue
    }
    if (argument === '--') {
      options = false
      continue
    }
    for (const flag of argument.slice(1)) {
      if (flag === 'l') {
        if (mode === 'silent') throw new CmpUsageError('conflicting -s and -l')
        mode = 'long'
        continue
      }
      if (flag === 's') {
        if (mode === 'long') throw new CmpUsageError('conflicting -s and -l')
        mode = 'silent'
        continue
      }
      throw new CmpUsageError(`invalid option -- '${flag}'`)
    }
  }
  return { mode, operands }
}

/**
 * The portable text of the errno codes a file open can surface.
 *
 * The host prints `cmp: <operand>: <strerror>`; the VFS error carries the code,
 * so the diagnostic keeps the same shape for the Worker's own read failures.
 */
const ERRNO_TEXT: Readonly<Record<string, string>> = Object.freeze({
  EACCES: 'Permission denied',
  EFBIG: 'File too large',
  EIO: 'Input/output error',
  EISDIR: 'Is a directory',
  ELOOP: 'Too many levels of symbolic links',
  ENAMETOOLONG: 'File name too long',
  ENOENT: 'No such file or directory',
  ENOMEM: 'Cannot allocate memory',
  ENOTDIR: 'Not a directory',
  ENXIO: 'No such device or address',
})

/** Render the strerror-shaped tail of one failed operand read. */
function describeOpenError(error: unknown): string {
  const coded = error as { code?: unknown; message?: unknown } | null
  const code = typeof coded?.code === 'string' && coded.code !== '' ? coded.code : undefined
  const text = code === undefined ? undefined : ERRNO_TEXT[code]
  if (text !== undefined) return text
  const message = typeof coded?.message === 'string' && coded.message !== '' ? coded.message : String(error)
  return message
}

/**
 * Read one operand through the shell filesystem.
 * @param fs - the shell filesystem.
 * @param cwd - virtual working directory.
 * @param operand - the operand as written.
 * @returns the file's bytes.
 */
async function readOperand(fs: IFileSystem, cwd: string, operand: string): Promise<Uint8Array> {
  const absolute = posix.normalize(fs.resolvePath(cwd, operand))
  return await fs.readFileBuffer(absolute)
}

/** Right-align an octal byte the way the host's `%3o` does. */
function octal(byte: number): string {
  return byte.toString(8).padStart(3, ' ')
}

/**
 * Find the first differing byte and its 1-based line number in the first file.
 * @param left - first file bytes.
 * @param right - second file bytes.
 * @returns the difference, or undefined when the shared prefix is equal.
 */
function firstDifference(left: Uint8Array, right: Uint8Array): { readonly offset: number; readonly line: number } | undefined {
  const limit = Math.min(left.byteLength, right.byteLength)
  let line = 1
  for (let index = 0; index < limit; index += 1) {
    if ((left[index] as number) !== (right[index] as number)) return { offset: index + 1, line }
    if ((left[index] as number) === 0x0a) line += 1
  }
  return undefined
}

/**
 * Build the `cmp` command over the Worker shell's filesystem.
 * @returns the command definition.
 */
export function createCmpCommand(): Command {
  return defineCommand('cmp', async (args, ctx): Promise<ExecResult> => {
    let parsed: CmpArguments
    try {
      parsed = parseCmpArguments(args)
    } catch (error) {
      if (error instanceof CmpUsageError) return { stdout: '', stderr: CMP_USAGE, exitCode: 2 }
      throw error
    }
    // `cmp` takes exactly two file operands on the implemented surface. The
    // host's optional skip1/skip2 words are not implemented, so three or more
    // operands are a refusal rather than a silently ignored argument.
    if (parsed.operands.length !== 2) return { stdout: '', stderr: CMP_USAGE, exitCode: 2 }
    const leftName = parsed.operands[0] as string
    const rightName = parsed.operands[1] as string
    const files: Uint8Array[] = []
    for (const operand of [leftName, rightName]) {
      try {
        files.push(await readOperand(ctx.fs, ctx.cwd, operand))
      } catch (error) {
        // -s is status-only, with one host quirk: a directory operand is
        // diagnosed even in silent mode, because the host checks the file type
        // before it silences the comparison output. Matching it keeps one
        // shape per failure instead of a Worker-only variant.
        const directory = (error as { code?: unknown } | null)?.code === 'EISDIR'
        if (parsed.mode === 'silent' && !directory) return { stdout: '', stderr: '', exitCode: 2 }
        return { stdout: '', stderr: `cmp: ${operand}: ${describeOpenError(error)}\n`, exitCode: 2 }
      }
    }
    const left = files[0] as Uint8Array
    const right = files[1] as Uint8Array
    const shortName = left.byteLength < right.byteLength ? leftName : rightName
    const eof = left.byteLength === right.byteLength ? '' : `cmp: EOF on ${shortName}\n`

    if (parsed.mode === 'long') {
      const limit = Math.min(left.byteLength, right.byteLength)
      const lines: string[] = []
      for (let index = 0; index < limit; index += 1) {
        const leftByte = left[index] as number
        const rightByte = right[index] as number
        if (leftByte === rightByte) continue
        lines.push(`${String(index + 1).padStart(6)} ${octal(leftByte)} ${octal(rightByte)}\n`)
      }
      const different = lines.length > 0 || eof !== ''
      return { stdout: lines.join(''), stderr: eof, exitCode: different ? 1 : 0 }
    }

    const difference = firstDifference(left, right)
    if (difference !== undefined) {
      if (parsed.mode === 'silent') return { stdout: '', stderr: '', exitCode: 1 }
      return {
        stdout: `${leftName} ${rightName} differ: char ${String(difference.offset)}, line ${String(difference.line)}\n`,
        stderr: '',
        exitCode: 1,
      }
    }
    if (eof !== '') {
      // A different length after an equal prefix is a difference, not an
      // error: `-s` still answers with status 1 and no output.
      if (parsed.mode === 'silent') return { stdout: '', stderr: '', exitCode: 1 }
      return { stdout: '', stderr: eof, exitCode: 1 }
    }
    return { stdout: '', stderr: '', exitCode: 0 }
  })
}
