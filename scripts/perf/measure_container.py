"""Measure the byte footprint of a phone-dsh app container.

The caller points this at a directory copied from a device (or at a fixture
generated by ``generate_container.py``).  The result is one JSON object:

* ``categories`` are mutually exclusive: every regular file is counted in
  exactly one of them, so ``sum(categories.values()) == total_bytes``.
  ``materialized`` is matched before any store name, because a real user
  workspace may contain directories called ``wal``, ``steps``, ``exec``,
  ``journal``, ``overlay``, ``response-log`` or ``transcript-snapshots``; those
  bytes are workspace bytes, not store bytes.  Store names only apply outside
  the materialized tree.
* ``caches`` is the app-private cache domain, ``Library/Caches/**``.  W3's
  rebuildable workspace tree lives at ``Library/Caches/pdsh/<workspace_id>``
  (``WorkspacePaths.cacheRoot`` in ``Sources/PhoneDSHLog/LogSupport.swift``).
  The system may purge the domain at any time and it is not Documents
  authoritative data; ``category_notes`` repeats that semantics in the JSON
  output.  Cache children are never attributed to a store, even when they are
  called ``response-log`` or ``overlay-*.tar``.
* ``app-support`` is app-private persistent data under
  ``Library/Application Support/**``, including the Bot's SQLite domain
  (``PhoneDSHBot/domain.sqlite``, ``domain.sqlite-wal``,
  ``domain.sqlite-shm``).  That data is durable but outside Documents: it is
  not a rebuildable cache and the system does not purge it, so it is neither
  ``caches`` nor ``other``.  Like the cache domain, its children are never
  attributed to a store, even when one is called ``wal``.
* ``breakdown`` splits the composite ``materialized`` category into the names
  the plan uses: session logs, workspace body, other materialized content; and
  it reports ``other`` separately.  These values are subsets, not extra bytes.
* a file with a hard-link count above one is counted once, at the first path
  that owns it; later links add zero bytes and increment
  ``hardlinks_deduplicated``.  This matches the plan's "移到 Library/Caches 的
  per-boot hard links must not be counted twice" requirement.

Usage:
    python3 scripts/perf/measure_container.py /tmp/container
    python3 scripts/perf/measure_container.py /tmp/container --pretty
    python3 scripts/perf/measure_container.py /tmp/container --output size.json
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence, Tuple

SCHEMA_VERSION = 1

# Every category is mutually exclusive.  The order matters only for readability;
# _classify() returns exactly one key.
CATEGORY_ORDER = (
    "wal",
    "materialized",
    "caches",
    "app-support",
    "response-log",
    "overlay",
    "journal",
    "steps",
    "exec",
    "transcript-snapshots",
    "other",
)

# The materialized tree is composed of these plan-level buckets.
MATERIALIZED_BUCKETS = ("sessions", "workspace")

# The app container's cache domain, `Library/Caches/**`.  W3's rebuildable
# workspace tree is `Library/Caches/pdsh/<workspace_id>` (`WorkspacePaths.cacheRoot`
# in `Sources/PhoneDSHLog/LogSupport.swift`, `cacheRoot(for:)` in
# `Sources/PhoneDSH/PhoneDSH.swift`); other app-private staging such as
# `Library/Caches/PhoneDSHImport` appears there too.  Everything under this
# domain is system-reclaimable and never Documents authoritative data, so it is
# one bucket.  The match is anchored on the `Library/Caches` path components so
# an unrelated user directory merely named `Caches` is not mistaken for it.
CACHE_ROOT_COMPONENTS = ("Library", "Caches")

# The app's persistent domain, `Library/Application Support/**`.  The Bot's
# SQLite store is `Library/Application Support/PhoneDSHBot/domain.sqlite`
# (`SQLiteDomainStore.applicationSupport()` in
# `Sources/PhoneDSHBot/Store/SQLiteDomainStore.swift`), with its `-wal` and
# `-shm` files beside it.  This is durable state outside Documents, not a
# rebuildable cache: the system does not purge the domain, so folding it into
# `caches` would claim the wrong recovery story, and folding it into `other`
# would make the Bot's store unattributable.  The match is anchored on the
# `Library/Application Support` path components (note the space and the case)
# so a user directory merely named `Application Support` stays `other`.  Like
# `Library/Caches`, it must be matched before every store-name check: a child
# directory called `wal` or `response-log` is Bot data, not a host store.
APP_SUPPORT_COMPONENTS = ("Library", "Application Support")

# Semantics that the numbers alone cannot convey.  These are copied into the
# JSON report under `category_notes`.
CATEGORY_NOTES = {
    "caches": (
        "App-private cache domain under Library/Caches. The W3 rebuildable tree "
        "(response-log bodies, transcript snapshots, overlay caches) lives at "
        "Library/Caches/pdsh/<workspace_id>. The system may purge this domain at any "
        "time and it is not Documents authoritative data; a purge is repaired by "
        "rebuilding the cache, never by recovering it as durable state."
    ),
    "app-support": (
        "App-private persistent data under Library/Application Support, outside "
        "Documents. The Bot's SQLite domain (PhoneDSHBot/domain.sqlite, "
        "domain.sqlite-wal, domain.sqlite-shm) lives here. Unlike caches, this "
        "domain is not system-reclaimable: it is not a rebuildable cache, the "
        "system does not purge it, and losing it loses durable agent domain data "
        "instead of regenerating it. It is reported separately from the "
        "Documents stores."
    ),
}


def _contains_components(parts: Sequence[str], components: Sequence[str]) -> bool:
    """True when ``components`` appear consecutively in ``parts``."""
    window = tuple(components)
    if not window:
        return False
    return any(tuple(parts[index:index + len(window)]) == window
               for index in range(len(parts) - len(window) + 1))


def _parts(root: Path, path: Path) -> Tuple[str, ...]:
    return path.relative_to(root).parts


def _classify(parts: Sequence[str]) -> str:
    joined = "/".join(parts)
    lower = joined.lower()
    name = parts[-1] if parts else ""

    # The materialized copy is authoritative and mirrors the user's workspace,
    # so its children may legitimately be named after any store.  This check
    # must come before every store-name check, otherwise workspace bytes are
    # reported as WAL/steps/exec/journal/overlay/response-log bytes.
    if "materialized" in parts:
        return "materialized"
    # Rebuildable content is its own bucket even when a child is named
    # `response-log`, `transcript-snapshots` or `overlay-*`.
    if _contains_components(parts, CACHE_ROOT_COMPONENTS):
        return "caches"
    # Durable Bot data, also its own bucket even when a child is named after a
    # store (`wal`, `response-log`).  These bytes are neither system-purgeable
    # caches nor Documents store bytes.  Keep this before every store-name
    # check, mirroring the cache rule above.
    if _contains_components(parts, APP_SUPPORT_COMPONENTS):
        return "app-support"
    if "wal" in parts:
        return "wal"
    if "response-log" in parts:
        return "response-log"
    if "transcript-snapshots" in parts:
        return "transcript-snapshots"
    if "steps" in parts:
        return "steps"
    if "exec" in parts:
        return "exec"
    if name.startswith("overlay-") or name.startswith("overlay-cache") or "overlay" in parts:
        return "overlay"
    if name.endswith(".xljournal") or "journal" in parts:
        return "journal"
    if lower.startswith("documents/") or "/documents/" in "/" + lower:
        return "other"
    return "other"


def _materialized_bucket(parts: Sequence[str]) -> str:
    if "materialized" not in parts:
        return "other"
    tail = parts[parts.index("materialized") + 1:]
    # Match the layout the host writes (WorkspacePaths): session journals live
    # under `materialized/home/sessions/**`; the workspace body under
    # `materialized/workspace/**`.  Positional matching keeps a workspace
    # subdirectory that happens to be called `sessions` in the workspace
    # bucket, mirroring the classification rule above.
    if tail[:2] == ("home", "sessions"):
        return "sessions"
    if tail[:1] == ("workspace",):
        return "workspace"
    return "other"


def _iter_files(root: Path) -> Iterable[Path]:
    for directory, dirnames, filenames in os.walk(root, followlinks=False):
        dirnames.sort()
        for filename in sorted(filenames):
            path = Path(directory) / filename
            try:
                if path.is_symlink() or not path.is_file():
                    continue
            except OSError:
                continue
            yield path


def measure(root: Path) -> dict:
    root = Path(root)
    if not root.is_dir():
        raise NotADirectoryError(f"{root} is not a directory")
    root = root.resolve()

    categories: Dict[str, int] = {name: 0 for name in CATEGORY_ORDER}
    files: Dict[str, int] = {name: 0 for name in CATEGORY_ORDER}
    breakdown: Dict[str, int] = {
        "sessions": 0,
        "workspace": 0,
        "materialized_other": 0,
        "other": 0,
    }
    seen_inodes: Dict[Tuple[int, int], str] = {}
    hardlinks_deduplicated = 0
    total = 0
    file_count = 0
    largest: List[dict] = []

    for path in _iter_files(root):
        try:
            info = path.stat()
        except OSError:
            continue
        relative = path.relative_to(root)
        parts = relative.parts
        category = _classify(parts)
        inode = (info.st_dev, info.st_ino)
        if info.st_nlink > 1:
            if inode in seen_inodes:
                hardlinks_deduplicated += 1
                # The inode is already accounted for; the path still exists but
                # adds no bytes.  Do not count it as a second file either, so
                # file_count stays a count of distinct byte sources.
                continue
            seen_inodes[inode] = str(relative)

        size = info.st_size
        categories[category] += size
        files[category] += 1
        total += size
        file_count += 1

        if category == "materialized":
            bucket = _materialized_bucket(parts)
            if bucket == "sessions":
                breakdown["sessions"] += size
            elif bucket == "workspace":
                breakdown["workspace"] += size
            else:
                breakdown["materialized_other"] += size
        elif category == "other":
            breakdown["other"] += size

        largest.append({"path": str(relative), "bytes": size})

    largest.sort(key=lambda item: (-item["bytes"], item["path"]))
    # A named, overlapping view for callers that want the plan's directory
    # names directly.  ``categories`` above is the disjoint partition; this
    # view intentionally repeats the materialized children (sessions and
    # workspace) so a report can print one number per named directory without
    # re-deriving the split.
    subdirectories = {
        "wal": categories["wal"],
        "materialized": categories["materialized"],
        "caches": categories["caches"],
        "app-support": categories["app-support"],
        "response-log": categories["response-log"],
        "overlay": categories["overlay"],
        "journal": categories["journal"],
        "steps": categories["steps"],
        "exec": categories["exec"],
        "sessions": breakdown["sessions"],
        "workspace": breakdown["workspace"],
        "transcript-snapshots": categories["transcript-snapshots"],
        "other": categories["other"],
    }
    result = {
        "schemaVersion": SCHEMA_VERSION,
        "root": str(root),
        "total_bytes": total,
        "file_count": file_count,
        "hardlinks_deduplicated": hardlinks_deduplicated,
        "categories": {name: categories[name] for name in CATEGORY_ORDER},
        "file_counts": {name: files[name] for name in CATEGORY_ORDER},
        "category_notes": {name: CATEGORY_NOTES[name]
                           for name in CATEGORY_ORDER if name in CATEGORY_NOTES},
        "breakdown": breakdown,
        "subdirectories": subdirectories,
        "largest_files": largest[:20],
    }
    if sum(categories.values()) != total:
        raise AssertionError("category totals do not add up to total_bytes")
    return result


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Report the byte footprint of a phone-dsh app container.")
    parser.add_argument("root", type=Path, help="container directory to measure")
    parser.add_argument("--output", type=Path, default=None,
                        help="write the JSON report here instead of stdout")
    parser.add_argument("--pretty", action="store_true",
                        help="indent the JSON (default: one line)")
    args = parser.parse_args(argv)

    try:
        report = measure(args.root)
    except (NotADirectoryError, OSError) as exc:
        print(f"measure_container: {exc}", file=sys.stderr)
        return 2

    text = json.dumps(
        report, ensure_ascii=False, sort_keys=True, indent=2 if args.pretty else None)
    if args.output is not None:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text + "\n", encoding="utf-8")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
